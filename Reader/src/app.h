#pragma once
// Приложение: окно, рабочее место, модели и экраны — один объект, и он же
// посредник между экранами.
//
// Экран не знает ни приложения, ни другого экрана, ни рабочего места: он
// показывает свою модель и сообщает о намерениях читателя через свой
// интерфейс `Actions`. Приложение реализует все `Actions` разом — забытое
// намерение не собирается — и знает всех: что чем сменяется, куда ведёт
// клавиша, что записать по дороге. Предметная логика — в библиотеке
// (`Workspace`, `ThemeList`, `KeyMap`, `SkinEditor`, `PageFlow`), здесь только
// связки, поэтому методы тонкие.
//
// Намерение и есть сценарий: метод `Actions` — корутина-член `detached_task`,
// и жизнь приложения на время её кадра держит промис (wxl.async: первый
// аргумент, считающий ссылки, — у члена это сам объект). Шаг, который ждёт и
// отдаёт значение, — `task<T>`-член; продолжений-колбэков нет.
//
// Отмена — деревом источников: у приложения один общий источник `stop_`, а
// каждый сценарий ждёт под своим, дочерним от него, — так ненужную задачу
// отменяет её владелец, не трогая остальных, а общий источник достаёт все
// разом. Его отменяет закрытие окна: ожидание кончается отменой, а сценарий —
// на этом ожидании. Записи токена не берут и доходят до конца.
//
// Файлы состояния книги, настроек и реестра книг пишут три цикла-корутины,
// которые держит приложение (`DeferredWrite`), — по одному писателю на файл:
// сценарии, которые меняют эти модели, идут разом и сами их не пишут.
// Перемена отодвигает запись своего цикла, «записать сейчас» будит его
// ожидание, а отмена, дошедшая и до них, кончает каждый после последней
// записи; её дожидается держатель цикла, умирая вместе с приложением.

#include <filesystem>
#include <utility>
#include <vector>

#include "CompositionWindow.h"
