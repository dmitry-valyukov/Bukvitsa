/// Путь в настройках — копия того, что в реестре, и она там ради быстрого
/// пути. Протух — спрашиваем реестр по guid; нет и там — читателю нечего
/// продолжать, и он хотел открыть книгу.
///
/// Короткая дорога — предзагрузка: книга, которую запуск начал читать заранее,
/// дочитывается (или уже прочитана) и открывается без второго чтения и
/// разбора, не спрашивая диск, — файл ей больше не нужен, даже если его успели
/// унести. Какую книгу она читает, сверять не надо: пока предзагрузка в поле,
/// ни одна книга не открывалась, и последняя в настройках — её.
///
/// Задача — в `continuing_`: второе нажатие останавливает первое на его
/// ожидании — вместе с предзагрузкой, которую оно забрало, — и идёт обычной
/// дорогой. Открытие, к которому дорога приходит, с предзагрузкой или без, —
/// уже не её: оно уходит в поле открытий, где открытие одно.
void App::continueReading() {
    continuing_ = reported(runContinueReading());
}

wxl::async::task<> App::runContinueReading() {
    auto const stop = cancellation_source{stop_.token()};

    if (preload_) {
        // Задача переходит в кадр сценария до ожидания: дождаться её может
        // лишь один, и сценарий, пришедший за это время, — второе нажатие или
        // открытие другой книги, — найдёт поле пустым.
        task<LoadedBook> preload = std::exchange(preload_, {});

        // Пусто — предзагрузка не удалась: у прочитанной книги пустого
        // состояния нет, а не удаться ей законно. Открытие — вне try: его
        // сбой — не сбой предзагрузки и молча не глотается.
        std::optional<LoadedBook> loaded;

        try {
            loaded.emplace(co_await preload);
        } catch (const operation_canceled_exception&) {
            // Её отменил владелец: открывается другая книга или закрыто окно —
            // продолжать нечего.
            co_return;
        } catch (const std::exception&) {
            // Файл не прочитался или книга испорчена — молча: обычная дорога
            // ниже прочитает её сама и скажет читателю поимённо.
        }

        if (loaded) {
            startOpeningPreloaded(std::move(*loaded));
            co_return;
        }
    }

    std::filesystem::path path = co_await ws_.lastBookPath(stop.token());

    if (path.empty()) {
        chooseBook();
        co_return;
    }

    startOpening(std::move(path));
}

/// Системный диалог модален, и пока он открыт, читалке всё равно делать
/// нечего; отказался читатель — ничего и не было. Ждать здесь нечего:
/// выбранная книга уходит в поле открытий.
void App::chooseBook() {
    std::filesystem::path path = askForBook(window_.handle());
    if (!path.empty()) startOpening(std::move(path));
}

/// Книга с пометкой «не найдена» открывается той же дорогой, что и всякая:
/// чтение файла и есть проверка, на месте ли он. Вернулся — регистрация при
/// открытии снимает пометку (`Library::add`), и карточка на полке перестаёт
/// быть приглушённой; нет — чтение кончается тем же словом читателю, что и
/// всякий сбой чтения файла. Отдельный вопрос диску «есть ли файл» перед
/// чтением ничего бы к этому не добавил.
void App::openBook(u16_text guid) {
    if (const BookEntry* known = ws_.library.find(guid)) startOpening(known->path);
}

/// Обходит каталог и добавляет из него книги — по одной, на глазах у читателя.
///
/// Каталог перечисляется на рабочем потоке; каждая книга читается там же;
/// разбирается она здесь, между двумя `co_await`, и сразу встаёт на полку. Ни
/// один шаг не ждёт остальных: первая книга появляется на полке, пока десятая
/// ещё не прочитана, — а окно всё это время отвечает, потому что
/// интерфейсный поток каждый раз возвращается в свой цикл сообщений.
///
/// Разбирается при этом документ, а не `Book`: реестру нужны метаданные и
/// обложка, а движок вёрстки с пагинатором книге, которую никто не открывал,
/// ни к чему (`Workspace::addFolder`). Каталог с этих пор наблюдаемый: каждый
/// запуск перепроверяет его (`rescanFolders`).
///
/// Задача — в `folderAdditions_`: каталог, добавленный следом, обходится
/// рядом, а прежний доходит до конца и до записи реестра.
void App::chooseFolder() {
    keepUntilDone(folderAdditions_, reported(runChooseFolder()));
}

wxl::async::task<> App::runChooseFolder() {
    auto const stop = cancellation_source{stop_.token()};

    const std::filesystem::path folder = askForFolder(window_.handle());
    if (folder.empty()) co_return;

    // Полка — прежде обхода: читатель, добавивший каталог, должен видеть, как
    // тот наполняется, а не пустой стартовый экран, за которым что-то
    // происходит.
    show(Screen::Library);

    ScanReport report;

    try {
        // Карточка — на каждую новую книгу сразу, пока обход идёт: реестр
        // ставит её в конец своих карточек, и полка, привязанная к ним,
        // встаёт одной карточкой больше, а не пересобирается — прогресс,
        // который уже проступил на соседях, остаётся.
        report = co_await ws_.addFolder(folder, stop.token());
    } catch (const last_error& failure) {
        // Каталог не перечислился: ни он, ни его книги в реестр не встали, и
        // писать нечего. Файл, который не прочитался или не записал обложку,
        // сюда не приходит — он в отчёте.
        notices_.post(noticeOf(L"Не удалось добавить каталог", folder.wstring(), failure));
        co_return;
    }

    // Каталог теперь наблюдаемый, а книги его — в очереди регистраций; и
    // каталог, и вставшие книги пока в памяти, файл пишет цикл реестра.
    // Пишется всегда, а не по `report.changed()`: новый каталог в реестре —
    // перемена и без книг (пустой каталог, каталог из одних известных). Книги,
    // вставшие после этой записи, отодвинут её снова (`bookRegistered`), а
    // обложки, которые не записались, назовёт `registrationRefused`. Отмена
    // кончает сценарий ещё на ожидании, мимо этой строки: её приносит
    // закрытие окна, а оно будит цикл реестра само.
    libraryWrite_.signal();

    postUnread(notices_, report.unread);
}

/// Перепроверка идёт в фоне, пока читатель смотрит на заставку или уже
/// читает: каталоги — один за другим, книги — по одной, между двумя
/// `co_await`. Неизменная книга стоит сверки с листингом, новая встаёт на
/// полку, пропавшая приглушается — карточки слышат это сами.
wxl::async::task<> App::rescanFolders() {
    auto const stop = cancellation_source{stop_.token()};

    const ScanReport report = co_await ws_.rescanFolders(stop.token());

    // Пометки перепроверка изменила только в памяти; файл пишет его цикл. Не
    // изменила — и писать нечего: тот же реестр лёг бы на диск заново. Книги,
    // которые она поставила в очередь, будят запись сами, вставая
    // (`bookRegistered`). Отмена кончает сценарий ещё на ожидании, мимо этой
    // строки: её приносит закрытие окна, а оно будит цикл реестра само.
    if (report.changed()) libraryWrite_.signal();

    postUnread(notices_, report.unread);
}

/// Читает книгу заранее, пока читатель смотрит на заставку и решает, чего он
/// хочет. Нажмёт «Продолжить чтение» — книга уже в памяти или на подходе, и
/// открытие обходится без второго чтения и разбора, то есть без самой долгой
/// своей части; не нажмёт — потеряна одна фоновая загрузка, которая шла в те
/// секунды, когда приложению всё равно нечего делать.
///
/// Вёрстки здесь нет и быть не может: она зависит от размера окна и настроек
/// вида. Заранее читается ровно то, что от вида не зависит: байты файла и
/// книга, развёрнутая в хранилище, с описанием и обложкой для реестра.
///
/// Задача стартует в этом вызове, как всякая `task`, и остаётся в поле: её
/// ждёт продолжение чтения, а бросает владелец — открытие книги. Здесь ничего
/// не проверяется и ничего не ждётся.
void App::preloadBook(std::filesystem::path path) {
    preload_ = ws_.readBook(std::move(path), preloadStop_.token());
}

/// Все дороги к книге кончаются здесь, и задача у открытий одна: книга,
/// выбранная следом, останавливает прежнее открытие на его ожидании — до смены
/// книги на полосе, на которой ожиданий уже нет.
void App::startOpening(std::filesystem::path path) {
    opening_ = reported(open(std::move(path)));
}

void App::startOpeningPreloaded(LoadedBook loaded) {
    opening_ = reported(openPreloaded(std::move(loaded)));
}

/// Предзагрузку дождалось продолжение чтения, и книга уже прочитана: остаётся
/// вторая половина открытия — под своим источником, как у всякого открытия.
wxl::async::task<> App::openPreloaded(LoadedBook loaded) {
    auto const stop = cancellation_source{stop_.token()};

    co_await openLoaded(std::move(loaded), stop.token());
}

/// Порядок здесь — это порядок обязательств. Сначала книга читается и
/// разбирается (и только если разобралась, старая уступает ей место), потом
/// (openLoaded) рабочее место регистрирует новую — шагом своей очереди
/// регистраций: обложка уходит в кэш, реестр меняется в памяти, — затем её
/// состояние и настройки, и лишь затем книга сменяется на полосе — одним
/// шагом, без ожиданий: циклы записи будятся на реестр, настройки и место
/// чтения прежней, места книги и полоса берут новую.
/// Каждый `co_await` — это выход в цикл сообщений: окно всё это время
/// живо, отвечает и перерисовывается — и прежняя книга на полосе читается
/// дальше.
///
/// Отмена кончает сценарий на чтении, на ожидании шага регистрации или на
/// открытии в рабочем месте, то есть всегда до смены книги на полосе: экран
/// остаётся при прежней.
///
/// Короткая дорога в начале одна: книга уже открыта (читатель вернулся к ней) —
/// показать. Предзагрузку открытие не берёт, а бросает: её дорога — только
/// «Продолжить чтение».
wxl::async::task<> App::open(std::filesystem::path path) {
    auto const stop = cancellation_source{stop_.token()};

    // Эта книга уже открыта — читатель просто вернулся к ней со стартового
    // экрана или с полки. Ни читать, ни разбирать заново нечего: полоса держит
    // её со всей вёрсткой и местом чтения, а реестр и настройки давно на неё
    // указывают. Остаётся показать.
    if (presenter_.isOpen() && presenter_.book()->path() == path) {
        show(Screen::Book);
        co_return;
    }

    // Читатель выбрал книгу, и предзагрузка больше не нужна, какую бы книгу
    // она ни читала: владелец отменяет её безусловно — ту, которую уже ждёт
    // продолжение чтения, — а ту, что ещё в поле, бросает: брошенная задача
    // кончается на своём ожидании, а чтение файла, ушедшее в пул, дорабатывает
    // само и ничего из её кадра не держит. Её ни ждать, ни спрашивать незачем:
    // книгу открытие читает само.
    preloadStop_.cancel();
    preload_ = {};

    // Пусто, пока книга не прочитана: у прочитанной пустого состояния нет, а
    // читается она под try, чьи обработчики кончают сценарий. Открытие — за
    // try: его сбой не выдаётся читателю за сбой чтения файла.
    std::optional<LoadedBook> loaded;

    try {
        loaded.emplace(co_await ws_.readBook(path, stop.token()));
    } catch (const operation_canceled_exception&) {
        co_return;   // отмена — не сбой: сказать читателю нечего
    } catch (const last_error& failure) {
        notices_.post(noticeOf(L"Не удалось прочитать файл книги", path.wstring(), failure));
        co_return;
    } catch (std::exception const& failure) {
        // Разговор с читателем, а не запись в лог: он только что выбрал этот
        // файл и вправе узнать, что с ним не так.
        u16_text const reason = unicode::assume_valid(failure.what()).to_utf16();
        notices_.post({L"Не удалось открыть книгу",
                       path.wstring() + L"\n\n" + std::wstring(reason.wchars())});
        co_return;
    }

    co_await openLoaded(std::move(*loaded), stop.token());
}

/// Вторая половина открытия — общая для открытия и продолжения чтения с
/// предзагрузки: книга прочитана и разобрана, дальше — рабочее место и полоса.
wxl::async::task<> App::openLoaded(LoadedBook loaded, cancellation_token stop) {
    // Под отменённым токеном открытие не начинается: книга не ставится и в
    // очередь регистраций.
    stop.throw_if_canceled();

    // Регистрация — шагом очереди рабочего места: та же книга, которую в этот
    // миг регистрирует перепроверка каталога, второй раз не ставится, и
    // открытие ждёт конца её шага. Ждёт под своим токеном: отменённое — а
    // отменяет его только выход, — ожидание кончается, а шаг идёт дальше:
    // книга встанет в реестр, только открытие её не дождётся, а отказ шага
    // ожидание не отдаст, и о нём скажет рабочее место (`registrationRefused`).
    // Запись — та, что отдал реестр, а не задуманная:
    // её guid — место чтения в books\{guid}.xml и последняя книга в настройках.
    // Сбой шага — запись обложки — приходит отсюда исключением и кончает
    // открытие сообщением читателю (reported): ни настройки, ни полоса книги
    // не узнают, на полосе остаётся прежняя.
    // Описание и обложка уходят в элемент очереди: книге они больше не нужны.
    auto const file = BookFile{.path = loaded.book->path(), .size = loaded.fileSize};
    not_null<intrusive_ptr<QueuedRegistration>> const queued = ws_.queueRegistration(
        std::move(loaded.description), loaded.book->characterCount(), std::move(loaded.cover), file);

    // Шаг кончился раньше, чем открытие до него дошло, — итог уже в элементе,
    // ждать нечего: событие конца шага зовётся один раз. Ожидание — отдельной
    // инструкцией, а не внутри условного выражения: co_await в выражении MSVC
    // переносит не во всяком. Ответ ожидания — копия того же итога, что
    // остаётся в элементе, и читается итог из элемента: на обоих путях,
    // кончился шаг раньше или его дождались, источник один, — а ответ
    // отбрасывается явно.
    if (!queued->done()) {
        static_cast<void>(co_await on_event(queued->ended(), stop));
    }
    const RegistrationOutcome& outcome = queued->outcome();
    if (!outcome) std::rethrow_exception(outcome.error());

    // Ссылкой: элемент держит этот кадр (`queued`), и запись в нём живёт до
    // конца открытия.
    const Registered& registered = *outcome;

    // Настройки, состояние — у рабочего места, настройки — только в памяти;
    // здесь — то, что видно: книга на полосе, её оглавление и закладки в
    // панели (панель идёт за списками сама), — и сигналы циклам записи.
    // Настройки уже укажут на новую книгу, а на полосе пока прежняя, и её
    // место пишется под guid её мест — их открытие не трогает.
    Opened opened = co_await ws_.openBook(registered.entry, std::move(stop));

    // Отсюда и до конца — ни одного ожидания: книга сменяется одним шагом.
    //
    // Реестр и настройки рабочее место изменило только в памяти, а пишут их
    // свои циклы — этот шаг их будит. Записать сейчас — то же ожидание цикла,
    // разбуженное владельцем: ждущий цикл просыпается внутри вызова и снимает
    // свой файл этим же ходом. Потому порядок трёх сигналов не меняет того,
    // что запишется, — он лишь повторяет порядок обязательств: реестр, затем
    // настройки, которые на книгу указывают, затем место прежней. Последнему
    // важно одно — стоять до смены книги: место чтения прежней снимается,
    // пока её место у полосы, а закладки и guid у мест книги; дальше их
    // возьмёт новая.
    libraryWrite_.signal();
    settingsWrite_.signal();
    stateWrite_.signal();

    // Оглавление и закладки — новой книги, пока прежняя ещё на полосе: строки
    // прежнего оглавления смотрят в её текст, и панель должна отпустить их
    // раньше, чем книга уйдёт. Находки прежнего поиска указывают в прежнюю
    // книгу.
    places_.open(std::move(opened.entry.guid), loaded.book->text(), std::move(opened.state.bookmarks));
    search_.clear();

    // Ведущий полосы добавляет свою ссылку на книгу; ссылка прочитанной уходит
    // с кадром этого шага.
    presenter_.open(loaded.book.get(), opened.state.charOffset);

    show(Screen::Book);
}

/// С паузой, а не «сейчас»: перепроверка ставит книги одну за другой, и
/// писать реестр на каждую незачем. Открытию запись нужна сразу — оно будит
/// цикл «сейчас» само, и пауза, начатая здесь раньше него, кончается тем же
/// ходом.
void App::bookRegistered(const Registered&) noexcept {
    // Шаг может кончиться и после закрытия окна — в докрутке выхода, когда
    // очередь окна уже остановлена: таймер цикла записи тогда трогать нельзя.
    // Последнюю запись реестра закрытие уже попросило; перемена, пришедшая
    // после неё, на диск не попадёт, и файл, чью запись она несла, следующая
    // перепроверка прочтёт заново.
    if (stop_.is_canceled()) return;

    libraryWrite_.restart();
}

/// Строки одного обхода сходятся в одно сообщение: пока оно открыто или ждёт
/// показа, сообщение с тем же заголовком дописывается в него строкой
/// (`Notices::post`) — так же, как непрочитанные файлы самого обхода
/// (`postUnread`).
void App::registrationRefused(const std::wstring& line) noexcept {
    // И после закрытия окна — тем же путём: шаг может кончиться в докрутке
    // выхода, когда диалог показывать уже не над чем, и тогда сообщение само
    // уходит строкой в stderr и в вывод отладчика (`Notices::post`). Сюда же
    // на выходе приходит и отказ шага, которого ждало открытие: отменённое
    // выходом ожидание итога не отдаёт, и рабочее место говорит о нём само, —
    // молча отказ не пропадает.
    notices_.post({L"Не удалось прочитать", line});
}

/// Поставить или снять и где ей лежать — решают места книги
/// (`BookPlaces::toggleBookmark`); панель идёт за списком закладок сама, а на
/// диск закладка уходит сразу — вместе с местом чтения, паузы не ждёт:
/// записать сейчас — то же ожидание цикла, разбуженное владельцем.
void App::toggleBookmark() {
    if (!presenter_.isOpen()) return;

    const uint32_t here = presenter_.position().get();
    places_.toggleBookmark(here, hintAt(presenter_.book()->text(), here));

    stateWrite_.signal();
}

/// Достраивает полку: у каждой книги свой файл состояния, и читаются они по
/// одному, уже после того, как полка показана.
///
/// Это и есть «библиотека наполняется по мере чтения»: карточки встают сразу,
/// а «прочитано 42%» проступает на каждой, как только её файл прочитан. Полка
/// с сотней книг не ждёт сотни обращений к диску, чтобы показать первую.
/// Строка — поле карточки (`ShelfCard::showState`): полка не пересобирается.
wxl::async::task<> App::fillProgress() {
    auto const stop = cancellation_source{stop_.token()};

    // Карточки — копией указателей: пока файлы читаются, обход каталога может
    // дополнить полку, а карточку, которую читают, держит сама копия.
    std::vector<intrusive_ptr<ShelfCard>> const cards(ws_.library.cards().begin(), ws_.library.cards().end());

    for (const intrusive_ptr<ShelfCard>& card : cards) {
        if (card->entry.characterCount == 0) continue;   // не открывалась — и читать нечего

        const BookState state = co_await ws_.readState(card->entry.guid, stop.token());
        card->showState(state);
    }
}

