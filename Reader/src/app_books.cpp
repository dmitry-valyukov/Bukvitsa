/// Путь в настройках — копия того, что в реестре, и она там ради быстрого
/// пути. Протух — спрашиваем реестр по guid; нет и там — читателю нечего
/// продолжать, и он хотел открыть книгу.
///
/// Короткая дорога — предзагрузка: книга, которую запуск начал читать заранее,
/// дочитывается (или уже прочитана) и открывается без второго чтения и
/// разбора, не спрашивая диск, — файл ей больше не нужен, даже если его успели
/// унести. Какую книгу она читает, сверять не надо: пока предзагрузка в поле,
/// ни одна книга не открывалась, и последняя в настройках — её.
detached_task App::continueReading() {
    auto const stop = cancellation_source{stop_.token()};

    if (preload_) {
        // Задача переходит в кадр сценария до ожидания: дождаться её может
        // лишь один, и сценарий, пришедший за это время, — второе нажатие или
        // открытие другой книги, — найдёт поле пустым.
        task<LoadedBook> preload = std::exchange(preload_, {});

        LoadedBook loaded;

        try {
            loaded = co_await preload;
        } catch (const operation_canceled_exception&) {
            // Её отменил владелец: открывается другая книга или закрыто окно —
            // продолжать нечего.
            co_return;
        } catch (const std::exception&) {
            // Файл не прочитался или книга испорчена — молча: обычная дорога
            // ниже прочитает её сама и скажет читателю поимённо.
        }

        if (loaded.book) {
            co_await openLoaded(std::move(loaded), stop.token());
            co_return;
        }
    }

    std::filesystem::path path = co_await ws_.lastBookPath(stop.token());

    if (path.empty()) {
        chooseBook();
        co_return;
    }

    open(std::move(path));
}

/// Системный диалог модален, и пока он открыт, читалке всё равно делать
/// нечего; отказался читатель — ничего и не было.
detached_task App::chooseBook() {
    std::filesystem::path path = askForBook(window_.handle());
    if (!path.empty()) open(std::move(path));
    co_return;
}

detached_task App::openBook(u16_text guid) {
    if (const BookEntry* known = ws_.library.find(guid)) open(known->path);
    co_return;
}

/// Обходит каталог и добавляет из него книги — по одной, на глазах у читателя.
///
/// Каталог перечисляется на рабочем потоке; каждая книга читается там же;
/// разбирается она здесь, между двумя `co_await`, и сразу встаёт на полку. Ни
/// один шаг не ждёт остальных: первая книга появляется на полке, пока десятая
/// ещё не прочитана, — а окно всё это время отвечает, потому что
/// интерфейсный поток каждый раз возвращается в свой цикл сообщений.
///
/// Разбирается при этом документ, а не `Book`: реестру нужны метаданные и
/// обложка, а движок вёрстки с пагинатором книге, которую никто не открывал,
/// ни к чему (`Workspace::addFolder`).
detached_task App::chooseFolder() {
    auto const stop = cancellation_source{stop_.token()};

    const std::filesystem::path folder = askForFolder(window_.handle());
    if (folder.empty()) co_return;

    // Полка — прежде обхода: читатель, добавивший каталог, должен видеть, как
    // тот наполняется, а не пустой стартовый экран, за которым что-то
    // происходит.
    show(Screen::Library);

    FolderAdded result;

    try {
        // Карточка — на каждую новую книгу сразу, пока обход идёт: реестр
        // ставит её в конец своих карточек, и полка, привязанная к ним,
        // встаёт одной карточкой больше, а не пересобирается — прогресс,
        // который уже проступил на соседях, остаётся.
        result = co_await ws_.addFolder(folder, stop.token());
    } catch (const system_exception& failure) {
        // Книги до сбоя полка уже показала, и реестр в памяти их знает: на
        // диск его — и при сбое.
        libraryWrite_.signal();
        notices_.post(noticeOf(L"Не удалось добавить каталог", folder.wstring(), failure));
        co_return;
    }

    // Реестр обход изменил только в памяти; файл пишет его цикл. Отмена
    // кончает сценарий ещё на ожидании, мимо этой строки: её приносит
    // закрытие окна, а оно будит цикл реестра само.
    if (result.added) libraryWrite_.signal();

    if (!result.unread.empty()) {
        std::wstring text;
        for (const std::wstring& line : result.unread) {
            if (!text.empty()) text += L"\n";
            text += line;
        }
        notices_.post({L"Не удалось прочитать", std::move(text)});
    }
}

/// Читает книгу заранее, пока читатель смотрит на заставку и решает, чего он
/// хочет. Нажмёт «Продолжить чтение» — книга уже в памяти или на подходе, и
/// открытие обходится без второго чтения и разбора, то есть без самой долгой
/// своей части; не нажмёт — потеряна одна фоновая загрузка, которая шла в те
/// секунды, когда приложению всё равно нечего делать.
///
/// Вёрстки здесь нет и быть не может: она зависит от размера окна и настроек
/// вида. Заранее читается ровно то, что от вида не зависит: байты файла и
/// разобранный документ с блоками.
///
/// Задача стартует в этом вызове, как всякая `task`, и остаётся в поле: её
/// ждёт продолжение чтения, а отменяет владелец — открытие книги. Здесь ничего
/// не проверяется и ничего не ждётся.
void App::preloadBook(std::filesystem::path path) {
    preload_ = ws_.readBook(std::move(path), preloadStop_.token());
}

/// Порядок здесь — это порядок обязательств. Сначала книга читается и
/// разбирается (и только если разобралась, старая уступает ей место), потом
/// (openLoaded) рабочее место регистрирует новую — обложка уходит в кэш, реестр
/// и настройки меняются в памяти — и читает её состояние, и лишь затем книга
/// сменяется на полосе — одним шагом, без ожиданий: циклы записи будятся на
/// реестр, настройки и место чтения прежней, места книги и полоса берут новую.
/// Каждый `co_await` — это выход в цикл сообщений: окно всё это время
/// живо, отвечает и перерисовывается — и прежняя книга на полосе читается
/// дальше.
///
/// Отмена кончает сценарий на чтении или на открытии в рабочем месте, то есть
/// всегда до смены книги на полосе: экран остаётся при прежней.
///
/// Короткая дорога в начале одна: книга уже открыта (читатель вернулся к ней) —
/// показать. Предзагрузку открытие не берёт, а отменяет: её дорога — только
/// «Продолжить чтение».
detached_task App::open(std::filesystem::path path) {
    auto const stop = cancellation_source{stop_.token()};

    // Эта книга уже открыта — читатель просто вернулся к ней со стартового
    // экрана или с полки. Ни читать, ни разбирать заново нечего: полоса держит
    // её со всей вёрсткой и местом чтения, а реестр и настройки давно на неё
    // указывают. Остаётся показать.
    if (view_.isOpen() && view_.book()->path() == path) {
        show(Screen::Book);
        co_return;
    }

    // Читатель выбрал книгу, и предзагрузка больше не нужна, какую бы книгу
    // она ни читала: владелец отменяет её безусловно — и ту, что ещё в поле, и
    // ту, которую уже ждёт продолжение чтения. Задачу из поля открытие
    // забирает и дожидается её конца: брошенная на ходу, она ждала бы рабочий
    // поток в деструкторе, синхронно.
    preloadStop_.cancel();

    if (preload_) {
        task<LoadedBook> preload = std::exchange(preload_, {});

        try {
            static_cast<void>(co_await preload);
        } catch (const std::exception&) {
            // Отменена или не удалась — неважно: книгу открытие читает само.
        }
    }

    LoadedBook loaded;

    try {
        loaded = co_await ws_.readBook(path, stop.token());
    } catch (const operation_canceled_exception&) {
        co_return;   // отмена — не сбой: сказать читателю нечего
    } catch (const system_exception& failure) {
        notices_.post(noticeOf(L"Не удалось прочитать файл книги", path.wstring(), failure));
        co_return;
    } catch (std::exception const& failure) {
        // Разговор с читателем, а не запись в лог: он только что выбрал этот
        // файл и вправе узнать, что с ним не так.
        u16_text const reason = unicode::assume_valid(failure.what()).to_utf16();
        notices_.post({L"Не удалось открыть книгу",
                       path.wstring() + L"\n\n" + std::wstring(reason.wchars())});
        co_return;
    }

    co_await openLoaded(std::move(loaded), stop.token());
}

/// Вторая половина открытия — общая для открытия и продолжения чтения с
/// предзагрузки: книга прочитана и разобрана, дальше — рабочее место и полоса.
wxl::async::task<> App::openLoaded(LoadedBook loaded, cancellation_token stop) {
    // Реестр, обложка, настройки, состояние — у рабочего места, реестр и
    // настройки — только в памяти; здесь — то, что видно: книга на полосе, её
    // оглавление и закладки в панели (панель идёт за списками сама), — и
    // сигналы циклам записи. Настройки уже укажут на новую книгу, а
    // на полосе пока прежняя, и её место пишется под guid её мест — их
    // открытие не трогает.
    Opened opened = co_await ws_.openBook(*loaded.book, loaded.fileSize, std::move(stop));

    // Отсюда и до конца — ни одного ожидания: книга сменяется одним шагом.
    //
    // Реестр и настройки рабочее место изменило только в памяти, а пишут их
    // свои циклы — этот шаг их будит. Записать сейчас — то же ожидание цикла,
    // разбуженное владельцем: ждущий цикл просыпается внутри вызова и снимает
    // свой файл этим же ходом. Потому порядок трёх сигналов не меняет того,
    // что запишется, — он лишь повторяет порядок обязательств: реестр, затем
    // настройки, которые на книгу указывают, затем место прежней. Последнему
    // важно одно — стоять до смены книги: место чтения прежней снимается,
    // пока её место у полосы, а закладки и guid у мест книги; дальше их
    // возьмёт новая.
    libraryWrite_.signal();
    settingsWrite_.signal();
    stateWrite_.signal();

    // Оглавление и закладки — новой книги, пока прежняя ещё на полосе: строки
    // прежнего оглавления смотрят в её блоки, и панель должна отпустить их
    // раньше, чем книга уйдёт. Находки прежнего поиска указывают в прежнюю
    // книгу.
    places_.open(std::move(opened.entry.guid), loaded.book->blocks(), std::move(opened.state.bookmarks));
    search_.clear();

    view_.open(std::move(loaded.book), opened.state.charOffset);

    show(Screen::Book);
}

/// Поставить или снять и где ей лежать — решают места книги
/// (`BookPlaces::toggleBookmark`); панель идёт за списком закладок сама, а на
/// диск закладка уходит сразу — вместе с местом чтения, паузы не ждёт:
/// записать сейчас — то же ожидание цикла, разбуженное владельцем.
detached_task App::toggleBookmark() {
    if (!view_.isOpen()) co_return;

    const uint32_t here = view_.position().get();
    places_.toggleBookmark(here, hintAt(view_.blocks(), here));

    stateWrite_.signal();
}

/// Достраивает полку: у каждой книги свой файл состояния, и читаются они по
/// одному, уже после того, как полка показана.
///
/// Это и есть «библиотека наполняется по мере чтения»: карточки встают сразу,
/// а «прочитано 42%» проступает на каждой, как только её файл прочитан. Полка
/// с сотней книг не ждёт сотни обращений к диску, чтобы показать первую.
/// Строка — поле карточки (`ShelfCard::showState`): полка не пересобирается.
detached_task App::fillProgress() {
    auto const stop = cancellation_source{stop_.token()};

    // Карточки — копией указателей: пока файлы читаются, обход каталога может
    // дополнить полку, а карточку, которую читают, держит сама копия.
    std::vector<intrusive_ptr<ShelfCard>> const cards(ws_.library.cards().begin(), ws_.library.cards().end());

    for (const intrusive_ptr<ShelfCard>& card : cards) {
        if (card->entry.characterCount == 0) continue;   // не открывалась — и читать нечего

        const BookState state = co_await ws_.readState(card->entry.guid, stop.token());
        card->showState(state);
    }
}

