#pragma once
// Словарь вида читалки: цвета и пресеты, которые носит больше одного экрана.
// Вид, нужный одному экрану, живёт в его .cpp; сюда переезжает то, что
// понадобилось второму, — чтобы одинаковое и выглядело, и называлось
// одинаково.
//
// Пресет — это скобки конструктора, которым дали имя: надевается безымянным
// аргументом (`Button{overlayButtonLook, u"…", onClick = …}`), и всё, что у
// употребления своё — текст, место в сетке, отступ, обработчик, — пишется
// рядом с ним. Пресет из одних значений — константа, его раскладывает
// компилятор. Кисть в нём записана цветом (`background = цвет`): сплошную
// кисть свойство строит само при надевании, и у каждого носителя она своя.
//
// Теги в константах — с квалификатором `wxl::dsl::`: директива на уровне
// пространства имён спрятала бы обычные слова под /W4 (C4459), а строителя,
// в котором её открыть, у константы нет. Функции, возвращающие пресет,
// открывают теги у себя, как всякий строитель разметки.

#include "ThemeBrush.h"
#include "pch.h"

namespace bukvitsa::reader {

/* ---------------- палитра ---------------- */

// Обстановка — ящики панели и диалог имени в мастере обложек: не бумага, а
// инструмент, и цвета у неё свои при любой теме страницы. Фон слегка
// прозрачный — под ним текст. wxl:: — потому что rgb() темы страницы
// (theme.h) даёт цвет Direct2D и заслонил бы этот.
inline constexpr wxl::Color kChrome = wxl::rgba(30, 30, 34, 0.95);
inline constexpr wxl::Color kChromeInk = wxl::rgb(232, 228, 220);
inline constexpr wxl::Color kChromeEdge = wxl::rgba(255, 255, 255, 0.2);

/// Приглушённые чернила светлых экранов — автор и прогресс на полке, автор
/// под «Продолжить чтение» на заставке: один тон, чтобы книга на обоих
/// экранах подписывалась одинаково.
inline constexpr wxl::Color kDimInk = wxl::rgb(138, 133, 125);

/// Кнопки карточки поверх картинки полупрозрачны: под ними снимок или
/// страница, и они должны просвечивать. Ставится визуалу кнопки, а не
/// тегом, — заставка ведёт к этой прозрачности анимацию появления.
inline constexpr float kOverlayButtonOpacity = 0.92f;

/* ---------------- кнопки карточки: заставка и мастер обложек ---------------- */

/// Кнопка карточки поверх картинки — на заставке и в мастере обложек: одна
/// ширина на всех, полужирная надпись, отбивка от соседок.
inline constexpr auto overlayButtonLook = wxl::Preset {
    wxl::dsl::width = 300.0f,
    wxl::dsl::height = 46.0f,
    wxl::FontWeight{600},
    wxl::Margin{0, 6},
    wxl::dsl::fontSize = 15.0f,
};

/// Главная кнопка той же карточки — действие по умолчанию, его зовёт Enter
/// («Продолжить чтение», «Сохранить»): та же кнопка, только выше и крупнее.
inline constexpr auto overlayMainLook = wxl::Preset {
    overlayButtonLook,
    wxl::dsl::height = 72.0f,
    wxl::dsl::fontSize = 19.0f,
};

/// Лицо кнопки отмены на той же карточке — чуть серее прочих: она уводит, а
/// не ведёт. Под указателем и нажатой — на шаг темнее, как у штатной кнопки,
/// но в своём сером: пока указатель над кнопкой, шаблон кладёт вместо фона
/// кисть состояния, которую ищет по имени в словаре темы, и кисть под тем же
/// именем на самом элементе находит первой. Состояния переключает фреймворк,
/// цвет — наш.
///
/// Функция, а не константа: кисть состояния — живой объект WinRT, а
/// константа пространства имён строится раньше, чем wxl поднимет среду.
/// Каждый вызов — свои кисти. Имена wxl — с квалификатором, теги — нет:
/// rgb() темы страницы (theme.h) ближе директивы и заслонил бы wxl::rgb.
inline auto cancelFaceLook() {
    using namespace wxl::dsl;

    return wxl::Preset {
        background = wxl::rgb(217, 214, 210),
        wxl::ThemeBrush{u"ButtonBackgroundPointerOver",
                        wxl::SolidColorBrush{wxl::rgb(208, 205, 201)}},
        wxl::ThemeBrush{u"ButtonBackgroundPressed", wxl::SolidColorBrush{wxl::rgb(199, 196, 192)}},
    };
}

/* ---------------- подписи ---------------- */

/// Подпись не длиннее двух строк, с многоточием в конце, — заголовок строки
/// в списках панели и название книги на полке.
inline constexpr auto twoLinesLook = wxl::Preset {
    wxl::dsl::textWrapping.wrap,
    wxl::dsl::maxLines = 2,
    wxl::dsl::textTrimming.characterEllipsis,
};

/// Подпись в одну строку с многоточием — вторая строка списка панели и
/// автор на полке.
inline constexpr auto oneLineLook = wxl::Preset {
    wxl::dsl::maxLines = 1,
    wxl::dsl::textTrimming.characterEllipsis,
};

}  // namespace bukvitsa::reader
