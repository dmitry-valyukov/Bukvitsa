#pragma once
// Всплывающая сноска.
//
// Сноски внизу полосы отложены не из лени: у них высота полосы зависит от
// того, что на неё попало, а что на неё попало — от высоты полосы, и пагинация
// перестаёт быть одним проходом. Всплывающая сноска этой связи не создаёт
// вовсе: страница уже сверстана, а сноска показывается поверх неё по щелчку и
// исчезает по Escape. Читателю она к тому же удобнее — не нужно искать глазами
// низ полосы и возвращаться обратно.
//
// Набирает сноску вёрстка (`typography::layoutNote`) тем же движком, что и
// книгу, только уже и мельче; здесь — место всплывашки, подложка и рисунок.
// Не поместилась — прокручивается.
//
// Рисунок — на виртуальной поверхности во весь рост сноски: комментарий в
// несколько тысяч слов выше любой текстуры устройства, а пиксели нужны только
// у окна прокрутки. Какие полосы рисовать и какие держать, решает
// `NoteBands` (bukvitsa.lib); здесь — рисунок строк в полосу и прокрутка,
// которая говорит, куда идёт.

// Свои заголовки со стандартными внутри — до всего, что тянет import
// wxl.core.
#include <optional>

#include "bukvitsa/reader/note_bands.h"
#include "bukvitsa/reader/note_frame.h"

#include "DrawingSurface.h"
#include "Object.h"
#include "pch.h"

// Последними: они импортируют wxl.core (тема — сама, книга — через модель,
// сноска — через заголовки вёрстки), после чего стандартный заголовок MSVC уже
// не принимает.
#include "bukvitsa/reader/book.h"
#include "bukvitsa/reader/theme.h"
#include "bukvitsa/typography/note.h"

namespace bukvitsa::reader {

class NotePopup {
public:
    explicit NotePopup(const wxl::Compositor& compositor);

    /// Элемент, который кладут поверх полосы набора.
    const wxl::UIElement& root() const { return root_; }

    /// Показывает тело сноски, стараясь встать рядом с её знаком.
    ///
    /// @param body   номер тела сноски (`typography::PlacedNote::body`): его
    ///               блоки книга уже развернула в своём хранилище.
    /// @param anchor низ знака сноски в координатах полосы, DIP.
    /// @param area   размер полосы: в него всплывашка и вписывается.
    /// @param scale  масштаб экрана: поверхность живёт в пикселях.
    void show(Book& book, uint32_t body, wxl::Point anchor, wxl::Size area,
              const Theme& theme, float fontSize, float scale);

    void hide();
    bool visible() const { return visible_; }

private:
    /// Поверхность под показанную сноску — окно прокрутки по ширине и подложка
    /// по росту, в пикселях (shownFrame_), от прежней сноски — ни пикселя.
    void prepareSurface() noexcept;

    /// Решётка полос заново — под рост сноски, окно прокрутки и предел
    /// устройства — и рисунок у текущего вида (viewTop_). Зовут показ и
    /// замена устройства: у обоих нарисованного нет.
    void startBands() noexcept;

    /// Шаг решётки на поверхности: отдать ушедшее, нарисовать новое.
    void applyBands(const NoteBandsStep& step) noexcept;

    /// Рисует свёрстанную сноску в кусок поверхности — строки, которые его
    /// задевают, цветом, в размер и масштаб, которые поставил show. noexcept:
    /// вёрстка — в show, раньше, а отказу рисования ответа нет — остановка.
    void drawPiece(const NotePixelRect& updatePiece) noexcept;

    /// Прокрутка говорит, куда идёт, до того как показать: следующий кадр и
    /// место, где встанет, дорисовываются заранее, ушедшее далеко отдаётся.
    void viewChanging(const wxl::ScrollViewer& viewer, wxl::ScrollViewerViewChangingEventArgs& args);

    /// Устройство под поверхностями композитора острова заменено (wxl):
    /// пиксели сноски пропали с прежним, а своего из его контекста она не
    /// держит — кисть заводится на каждый рисунок. У показанной решётка
    /// начинается заново — с пределом нового устройства — и рисуется текущий
    /// вид; скрытую нарисует следующий показ. Слушатель держателя
    /// deviceWatch_: noexcept — ход очереди потока исключению никому не
    /// отдаст.
    void renderingDeviceReplaced() noexcept;

    wxl::Compositor compositor_;

    /// Место прокрутки сноски — к нему привязана прокрутка в обе стороны:
    /// показ ставит ноль, и новая сноска открывается с начала, а куда
    /// прокрутил читатель, поле узнаёт от прокрутки само. Выше контролов:
    /// привязка к нему — в их скобках.
    observable<double> scrollTop_{0.0};

    // Контролы — поля, построенные вместе со всплывашкой: дети выше корня.
    wxl::Grid paper_;   ///< подложка ростом с текст сноски и полем над ним и под ним
    wxl::SpriteVisual sprite_;
    wxl::Border root_;
    std::optional<wxl::VirtualDrawingSurface> surface_;

    typography::NoteLayout body_;   ///< тело показанной сноски; шрифты — у движка книги
    bool visible_ = false;

    /// Чем нарисована показанная сноска: цвет текста темы, мера всплывашки
    /// (note_frame.h: поверхность и окно прокрутки в пикселях) и масштаб
    /// экрана. Помнится затем, чтобы дорисовывать её при прокрутке и нарисовать
    /// заново после замены устройства — тема и мера к тому времени у show уже
    /// не в руках.
    D2D1_COLOR_F ink_{};
    NoteFrame shownFrame_;
    float scale_ = 1.0f;

    /// Верх показанного вида в DIP: у новой сноски — куда её поставил сброс
    /// прокрутки, дальше — следующий кадр, о котором сказала прокрутка. От него
    /// рисует замена устройства.
    double viewTop_ = 0.0;
    /// Какие полосы поверхности нарисованы и держатся.
    NoteBands bands_;

    /// Замена потерянного устройства — последней: слушатель рисует всем, что
    /// выше, и снимается сам, умирая раньше.
    wxl::RenderingDeviceWatch<&NotePopup::renderingDeviceReplaced> deviceWatch_;
};

}  // namespace bukvitsa::reader
