#pragma once
// Мастер обложек: читатель укладывает кривые по краям листа своего снимка.
//
// Мастер — не отдельный экран, а оверлей поверх полосы набора: под ним
// BookView рисует снимок и текущую читаемую страницу, изогнутую по
// редактируемым кривым (предпросмотр включает setPreview). Сам мастер рисует
// только сетку: у каждой из двух границ разворота — верха и низа — своя
// кривая из девяти точек, по пять на лист, а средняя стоит на корешке и общая
// обоим листам; точки тянутся мышью в обе оси, кроме точки корешка — та
// только по вертикали, середина у неё своя; между верхней и нижней кривыми
// идут интерполированные линии — подсказка, как лягут строки. Карта
// изгиба пересчитывается по отпусканию точки, а не на каждом движении:
// тянуть должно быть легко.
//
// Все координаты живут в долях ширины и высоты, поэтому смена размеров окна
// ничего не теряет. Диска здесь нет: снимок мастер только проверяет, а копию
// кладёт приложение — через свой рабочий поток. Что делать с точками и именем
// — куда встаёт перетащенная точка, в какой кружочек попал указатель, что
// сохранять, — решает модель правки (`SkinEditor`); мастер её показывает.

#include <filesystem>
#include <optional>
#include <vector>

#include "DrawingSurface.h"
#include "Object.h"
#include "pch.h"

// Последним: модель правки импортирует wxl.core, после чего стандартный
// заголовок MSVC уже не принимает.
#include "bukvitsa/reader/skin_editor.h"

namespace bukvitsa::reader {

/// Мастер обложек. Владеет своим деревом, сеткой и моделью правки; исполнитель
/// намерений — владельца, живёт дольше мастера.
class SkinWizard : private noncopyable {
public:
    /// Что мастер умеет попросить. Реализует владелец; ждёт ли дело диска,
    /// мастеру знать незачем: сценарий и его задачу держит владелец.
    class Actions {
    public:
        /// «Сохранить», имя уже есть и годится. Сохранение одно за раз: следующее
        /// мастер не начнёт, пока владелец не скажет, что это кончилось
        /// (`saveEnded` с его номером), — удачей или отказом.
        virtual void saveSkin(SkinSave save) = 0;
        /// «Выбрать другое изображение».
        virtual void chooseAnotherImage() = 0;
        /// «Выйти из мастера обложек» — и Escape.
        virtual void leaveWizard() = 0;

    protected:
        ~Actions() = default;
    };

    SkinWizard(const wxl::Compositor& compositor, Actions& actions);

    /// Оверлей, который кладётся поверх полосы набора.
    const wxl::UIElement& root() const { return root_; }

    /// Начинает новую обложку с этого снимка: точки на начальных местах, имя
    /// пустое. Снимок к этому моменту проверен владельцем: сценарий
    /// приложения прочитал и раскодировал его рабочим местом
    /// (`Workspace::probeImageAsync`), а мастеру достался путь уже
    /// проверенного снимка. Диска мастер не касается, сам снимок для показа
    /// полосе приносит владелец.
    void openNew(std::filesystem::path image);

    /// Открывает существующую обложку на правку: её кривые, её снимок, её
    /// имя в диалоге сохранения. Снимок проверен владельцем, как у openNew().
    /// @param image где лежит её снимок: это знает рабочее место, не мастер.
    void openEdit(const Skin& skin, std::filesystem::path image);

    void show();

    /// Скрывает мастер — единственная дорога из него: выход, Escape,
    /// сохранение и уход с полосы (App::show) идут сюда через владельца.
    /// Полосе показывать становится нечего (`shownPreview` пуст).
    void hide();

    bool isOpen() const { return open_; }

    /// Сохранение с этим номером кончилось: «Сохранить» снова сохраняет.
    /// Номер прежнего открытия мастера ничего не меняет (`SkinEditor::saveEnded`).
    /// @return это было сохранение правки, открытой сейчас.
    bool saveEnded(uint64_t ticket) { return editor_.saveEnded(ticket); }

    /// Что полоса показывает под мастером — обложка и её снимок; пусто —
    /// мастер закрыт. Меняют его открытие, другой снимок, отпущенная точка и
    /// скрытие (`SkinEditor::shownPreview`); сам снимок полосе приносит
    /// владелец. Только на чтение.
    observable<std::optional<SkinPreview> const>& shownPreview() { return editor_.shownPreview(); }

private:
    void buildTree();

    /// Пересчитывает поверхность сетки под размер окна и масштаб экрана.
    bool resizeSurface();

    /// Направляющие и точки — в поверхность сетки. noexcept: отказу рисования
    /// ответа нет — остановка.
    void redraw() noexcept;

    /// Устройство под поверхностями композитора заменено (wxl): пиксели сетки
    /// пропали с прежним, а своего из его контекста мастер не держит — кисти
    /// заводятся на каждый рисунок. Сетка рисуется заново. Слушатель
    /// держателя deviceWatch_: noexcept — ход очереди потока исключению никому
    /// не отдаст.
    void renderingDeviceReplaced() noexcept;

    /// Диалог имени открылся или закрылся (`SkinEditor::naming`). Закрывает его
    /// и сама модель — другим снимком, правкой другой обложки, начатым
    /// сохранением, — и фокус с упавшего поля ушёл бы куда придётся, а Enter и
    /// Escape мастера молчали бы до щелчка: закрытый под показанным мастером
    /// диалог возвращает фокус корню. Привязка фокуса поля этого не сделает:
    /// её «нет» — не просьба. Слушатель держателя namingWatch_: noexcept —
    /// событию поля исключение отдать некому.
    void namingChanged(bool naming) noexcept;

    /// Сетка в DIP — то, во что модель правки переводит доли снимка.
    SkinEditor::Size area() const { return {width_, height_}; }

    /// «Сохранить» — и оно же действие по умолчанию на Enter. У правки
    /// старой обложки имя уже есть, и диалог не показывается — сохранение
    /// идёт сразу; имя спрашивается только у новой. При открытом диалоге имени
    /// — его «ОК». Пока сохранение идёт, не делает ничего.
    void saveRequested();

    /// «ОК» диалога имени — и Enter в нём.
    void confirmName();
    /// «Отмена» диалога имени — и Escape в нём.
    void cancelName();

    // Обработчики корня: клавиши на пути вниз, размер, указатель.
    void keyDown(wxl::Object const& sender, wxl::KeyRoutedEventArgs& args);
    void sizeChanged();
    void pointerPressed(wxl::Grid const& self, wxl::PointerRoutedEventArgs& args);
    void pointerMoved(wxl::Grid const& self, wxl::PointerRoutedEventArgs& args);
    void pointerReleased(wxl::Object const& sender, wxl::PointerRoutedEventArgs& args);

    Actions& actions_;
    wxl::Compositor compositor_;

    /// Редактируемые кривые, имя, диалог имени, снимок и то, что показывает
    /// полоса: модель одна на всю жизнь мастера. Выше контролов: поле имени
    /// привязано к её `name`, видимость диалога — к её `naming`. Диалог — свой
    /// оверлей, а не системное окно: он живёт поверх той же страницы, и
    /// «Отмена» возвращает ровно туда, где читатель был.
    SkinEditor editor_;

    /// В фокусе ли поле имени — к нему привязан фокус поля в обе стороны.
    /// Идёт за `SkinEditor::naming`: открылся диалог — поле просит фокус.
    /// Следует, а не привязано к нему прямо: слушатель приложения зовётся после
    /// всех привязок поля, и панель имени к этому времени уже видна, — на
    /// свёрнутой фокус не встал бы.
    observable<bool> nameFocused_{false};

    // Контролы — поля, построенные вместе с мастером: дети выше корня.
    wxl::Grid surfaceHost_;   ///< несёт визуал сетки
    wxl::SpriteVisual visual_;   ///< в дереве с первой поверхностью
    std::vector<wxl::DrawingSurface> surface_;   ///< ноль или одна — как листы полосы

    wxl::Grid root_;

    bool open_ = false;

    /// Кружочек, который тянут; пусто — не тянут.
    std::optional<SkinEditor::Grip> dragged_;

    /// Размер в DIP и масштаб экрана; поверхность — в их произведении.
    float width_ = 0.0f;
    float height_ = 0.0f;
    float scale_ = 1.0f;

    /// Подписки — последними: их слушатели трогают то, что выше, и снимаются
    /// сами, умирая раньше. Диалог имени — его закрытие возвращает фокус корню.
    change_watch<observable<bool const>, &SkinWizard::namingChanged> namingWatch_;

    /// Замена потерянного устройства: слушатель рисует всем, что выше.
    wxl::RenderingDeviceWatch<&SkinWizard::renderingDeviceReplaced> deviceWatch_;
};

}  // namespace bukvitsa::reader
