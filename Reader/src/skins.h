#pragma once
// Обложки: снимок раскрытой книги и кривые его краёв, настроенные читателем.
//
// Встроенная тема с фотографией гнёт строки идеализацией — синусом, одним на
// все снимки. У настоящего снимка нелинейность своя, причём у каждой из
// четырёх границ — верха и низа левого и правого листа — своя собственная:
// лист лежит как лежит, и его края не обязаны повторять друг друга. Поэтому
// обложка хранит две кривые — верхнюю и нижнюю границу разворота — по девять
// точек каждая: пять на левый лист, пять на правый, а средняя, на корешке,
// общая обоим — там листы сходятся, и край там один. Пяти точек хватает
// лежащей на боку букве S, которой края листа и описываются. Точки
// расставляет мастер (skin_wizard.h), а вёрстка строит по ним карту изгиба
// вместо синуса.
//
// Все координаты — в долях ширины и высоты снимка, а не в пикселях: обложка
// не знает ни размера окна, ни масштаба экрана, и настройка, снятая в одном
// окне, верна в любом. Статья о самом изгибе — doc/page-warp.md.

#include <array>
#include <filesystem>
#include <span>
#include <string>
#include <string_view>
#include <vector>

namespace bukvitsa::reader {

/// Кривая одной границы разворота — верхней или нижней: девять точек, каждая
/// со своими X и Y. Левый лист описывают точки от нулевой до `kSpine`, правый
/// — от `kSpine` до последней; точка `kSpine` стоит на корешке и принадлежит
/// обоим листам сразу, поэтому в корешке край непрерывен — хотя и может
/// ломаться: бумага там сгибается.
///
/// По X точка корешка всегда на середине, `kSpineX`: там режутся страницы
/// разворота и лежит тень корешка (book_view.cpp), и излом кромки обязан
/// стоять там же. Ходит она только по вертикали; мастер, чтение реестра и
/// встроенные обложки это держат.
struct EdgeCurve {
    static constexpr int kPoints = 9;
    static constexpr int kSpine = 4;          ///< номер точки корешка
    static constexpr float kSpineX = 0.5f;   ///< её X: середина разворота

    std::array<float, kPoints> x;   ///< по возрастанию, доли ширины
    std::array<float, kPoints> y;   ///< доли высоты
};

/// Одна обложка. Имя вводит читатель, и оно же — ключ реестра: сохранить
/// обложку под старым именем значит заменить её.
struct Skin {
    std::wstring name;
    std::wstring image;   ///< имя файла снимка; где он лежит, говорит `system`

    /// Системная — приехала вместе с программой, а не заведена читателем.
    /// Снимок такой лежит в `Assets` рядом с исполняемым, а не в
    /// `skinDirectory()`; в реестр она не пишется и из него не удаляется,
    /// поэтому кнопки удаления у неё нет. Спрашивать про снимок надо
    /// `skinImagePath()`, а не складывать путь руками.
    bool system = false;

    EdgeCurve top;
    EdgeCurve bottom;
};

/// Начальный отступ прямых краёв и крайних точек кривой от кромок снимка.
inline constexpr float kEdgeInset = 1.0f / 40.0f;

/// Докуда мастер разрешает утянуть точку края: от кромки до четверти высоты.
inline constexpr float kEdgeReach = 0.25f;

/// Обложка с точками на начальных местах: края — прямые в `kEdgeInset` от
/// кромок, точки каждой кривой — равномерно от `kEdgeInset` у левой кромки до
/// `kEdgeInset` у правой, так что средняя стоит ровно на середине — там, где
/// у разворота корешок.
Skin defaultSkin();

/// Обложки, которые приезжают вместе с программой: «Антиквариат», «Томик»,
/// «Брошюра». Их снимки лежат в `Assets`, а точки краёв выписаны в коде —
/// поэтому на чистой машине, где нет ещё ни настроек, ни реестра, читатель
/// видит их такими же, какими их видим мы.
///
/// Точки сняты мастером с этих самых фотографий и перенесены сюда как есть.
/// До этого «Антиквариат» гнул строки формулой — куполом синуса, одним на
/// любой снимок; формула идеализирует, а у настоящей фотографии каждая из
/// четырёх границ своя, и совпадения с ней у синуса нет ни в одной точке.
/// Описание сделано руками один раз и больше не меняется — значит, его место
/// в программе, а не в настройке, которой на новой машине ещё нет.
std::span<const Skin> systemSkins();

/// Где лежит снимок обложки. Единственное место, которое это знает: у
/// системной — `Assets` рядом с исполняемым, у заведённой читателем — копия в
/// `skinDirectory()`.
std::filesystem::path skinImagePath(const Skin& skin);

/// Кромка, готовая к вычислению: точки кривой и касательные в них. Строится
/// один раз на проход — по столбцам карты изгиба или по линиям сетки
/// мастера, — чтобы касательные не считались заново на каждом столбце.
///
/// Каждый лист — монотонный кубический сплайн Эрмита через свои пять точек.
/// Касательные по Фричу и Батленду: взвешенное гармоническое среднее наклонов
/// соседних хорд, ноль там, где хорды меняют знак; крайние — по хорде
/// крайнего отрезка. Кривая проходит через каждую точку и между соседними
/// точками не выходит за их значения: кружочки мастера лежат на самой кромке,
/// и тянуть кружочек значит тянуть кромку ровно туда. У корешка касательные
/// каждого листа свои, так что кромка там может ломаться, как бумага на
/// сгибе. Иксы точек строго возрастают — это держат мастер и чтение реестра.
class EdgeSpline {
public:
    explicit EdgeSpline(const EdgeCurve& curve);

    /// Значение кромки в столбце `u` (доля ширины); левее первой точки и
    /// правее последней — значение крайних.
    float at(float u) const;

private:
    /// Точек у листа: от наружной кромки до корешка включительно.
    static constexpr size_t kLeaf = static_cast<size_t>(EdgeCurve::kSpine) + 1;

    const EdgeCurve& curve_;

    /// Касательные по листам: у левого — к точкам 0…4, у правого — к 4…8.
    /// Точка корешка входит в оба листа, и касательных у неё две.
    std::array<float, 2 * kLeaf> slope_;
};

/// Реестр обложек — skins.xml. Читается и пишется целиком, как и остальные
/// файлы читалки; байты приносит и уносит `Io`.
class Skins {
public:
    /// Версия формата: незнакомое игнорируется, а не роняет разбор. Вторая —
    /// четыре независимые кривые по пять точек вместо девяти общих вертикалей
    /// первой; третья — две кривые по девять точек с общей точкой корешка.
    /// Вторая читается: две её точки у корешка — последняя левого листа и
    /// первая правого — сводятся в одну: на середине, высотой посередине
    /// между ними.
    static constexpr int kVersion = 3;

    /// Разбирает skins.xml. Пусто или битое — реестр просто пуст: обложки не
    /// то, ради чего стоит не запуститься.
    void loadFrom(std::string xml);

    /// Текст skins.xml — то, что уходит в `Io::writeFile`.
    std::string toXml() const;

    const std::vector<Skin>& list() const { return skins_; }

    const Skin* find(std::wstring_view name) const;

    /// Добавляет обложку или заменяет одноимённую: имя — ключ.
    void put(Skin skin);

    /// Убирает обложку по имени; `false` — такой в реестре нет.
    ///
    /// Снимок остаётся лежать в `skinDirectory()`, и это не забывчивость:
    /// одна и та же копия картинки бывает у двух обложек — мастер, сохранив
    /// открытую обложку под другим именем, заводит вторую с тем же именем
    /// файла. Ссылок на файл никто не считает, так что уносить его вместе с
    /// обложкой значило бы иногда ломать соседнюю.
    bool remove(std::wstring_view name);

private:
    std::vector<Skin> skins_;
};

/// Путь к skins.xml.
std::filesystem::path skinsPath();

/// Каталог копий снимков. Копий, а не ссылок на оригинал: обложка не должна
/// умереть вместе с перемещённым или стёртым исходным файлом.
std::filesystem::path skinDirectory();

}  // namespace bukvitsa::reader
