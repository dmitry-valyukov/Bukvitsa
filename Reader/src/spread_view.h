#pragma once
// SpreadView — разворот в покое: две страницы на сцене окна и растры, в
// которые разворот рисуется.
//
// Разворот растеризуется один раз, а показывается сколько угодно раз: в покое
// его носят обе страницы, в полёте книжного переворота — перелистываемая
// страница и приходящая половина листа, а уходящая половина берёт прежний.
// Поэтому растров здесь пул, а осевший разворот — указатель на один из них, а
// не своя поверхность: посадка листа переставляет указатель, ничего не рисуя и
// ничем не меняясь. Растр свободен, когда его не носит ни страница, ни летящий
// лист, — такой и берёт следующий переворот. Единица растра — разворот: растр
// несёт обе страницы, а визуалы страниц обрезаны каждый до своей половины.
//
// Что рисовать, разворот не знает: рисует владелец (`Painter`) — то, что поток
// страниц показывает сейчас. Анимации не знает тоже: листы и то, какие растры
// они держат, — у стратегии переворота (`TurnAnimation`).
//
// Владение: визуалы страниц и растры — свои; композитор и сцена — окна.

// Свои заголовки со стандартными внутри — до всего, что тянет import
// wxl.core: стандартный заголовок, включённый после импорта, MSVC уже не
// принимает.
#include <array>
#include <functional>
#include <optional>
#include <vector>

#include "DrawingSurface.h"
#include "pch.h"

namespace bukvitsa::reader {

/// Плотность тени у самой кромки и в середине спада. Тут и у остальных теней
/// записана только прозрачность: тон у всех общий и берётся из темы, потому
/// что тень на бумаге уходит в её же тон, а не в серое.
///
/// На четверть легче прежнего: у корешка тень читалась провалом, а не
/// углублением, и съедала первые буквы строки. Той же парой меряется средник
/// разворота — он обязан совпасть с полутоном изгиба, иначе подмена в конце
/// переворота видна ступенькой. Потому и лежит она здесь, у разворота: средник
/// рисуется в его растр, а тени переворота берут её отсюда.
inline constexpr uint32_t kFoldNear = 0x70000000;
inline constexpr uint32_t kFoldMid = 0x28000000;

/// Притенение самого листа у сгиба — то, чем плоская бумага получает
/// объём: у корешка лист отходит от страницы и уходит в тень собственного
/// изгиба. Это не тень на чём-то другом, а полутон на самой бумаге, потому
/// полоска и лежит ребёнком листа: его же клип не даёт ей вылезти на страницу
/// под ним, пока лист узкий. Плотность — ровно та, что у тени поднятой
/// бумаги, и это не совпадение, а требование: средник разворота обязан быть
/// того же цвета, что тень при листании, а полутон обязан совпадать со
/// средником (см. alphaOf) — значит, все трое носят одну плотность.
inline constexpr float kBendOfWindow = 0.045f;
inline constexpr uint32_t kBendNear = kFoldNear;
inline constexpr uint32_t kBendMid = kFoldMid;
inline constexpr float kBendMidStop = 0.45f;

/// Прозрачность из записанного цвета. Нужна затем, чтобы средник и полутон
/// изгиба брали её из одного места: они обязаны совпасть, иначе подмена в
/// конце переворота будет видна ступенькой.
constexpr float alphaOf(uint32_t argb) {
    return static_cast<float>((argb >> 24) & 0xFFu) / 255.0f;
}

/// Разворот на сцене окна: две страницы-визуала и пул растров разворота.
/// Визуалы страниц и растры — свои; композитор, сцена и рисование — владельца.
class SpreadView : private noncopyable {
public:
    /// Растр разворота — номер в пуле. Номер, а не указатель: пул растёт и
    /// отпускает растры, а номер у растра свой, пока он жив.
    using RasterId = uint32_t;

    /// «Растра нет»: страница, которую ещё ни во что не одели.
    static constexpr RasterId kNoRaster = ~RasterId{0};

    /// Стороны разворота — номера страниц-визуалов.
    static constexpr size_t kLeftPage = 0;
    static constexpr size_t kRightPage = 1;

    /// Рисует в данный ему контекст то, что поток страниц показывает сейчас.
    /// Контекст приходит с преобразованием атласа поверхности, в пикселях.
    using Painter = std::function<void(ID2D1DeviceContext*)>;

    /// Ставит обе страницы на сцену под всем, что на ней будет, скрытыми: их
    /// покажет show(true).
    SpreadView(const wxl::Compositor& compositor, const wxl::ContainerVisual& scene,
               Painter painter);

    /// Мера полосы в пикселях. Первая заводит осевший растр; дальше растры
    /// меняют размер, а не пересоздаются: кисти, которые их уже показывают
    /// (страницы, листы, задник окна), продолжают показывать их же.
    void resize(wxl::SizeInt32 pixels);

    /// Есть ли куда рисовать: мера уже пришла.
    bool measured() const { return !rasters_.empty(); }

    /// Страницы на экране — или нет: вне чтения их быть видно не должно.
    /// Пока они скрыты, их не одевают — ни redraw, ни посадка листа: одевает
    /// их первый redraw после показа.
    void show(bool shown);
    bool shown() const { return shown_; }

    /// Рисует нынешний разворот в этот растр. Растр осевший — и страницы
    /// показаны — обе одеваются в него; любой другой (растр самого нового
    /// листа в полёте книжного переворота) страниц не трогает: неперелистываемой
    /// до посадки листа положено старое.
    void redraw(RasterId target);

    /// Осевший разворот — растр, который носят обе страницы в покое; в полёте
    /// книжного переворота его носит неперелистываемая страница.
    RasterId settledRaster() const { return settledRaster_; }

    /// Осевшим становится этот растр — без отрисовки и без одевания: страницы
    /// одевает тот, кто знает, какую пора (посадка листа, redraw).
    void settleOn(RasterId raster) { settledRaster_ = raster; }

    const wxl::DrawingSurface& raster(RasterId raster) const;

    /// Страница-визуал стороны разворота и растр, который она носит.
    const wxl::SpriteVisual& pageVisual(size_t side) const;
    RasterId pageRaster(size_t side) const { return pageRasters_[side]; }

    /// Одевает страницу в растр: кисть растянута на весь визуал, крой у
    /// страницы свой.
    void dressPage(size_t side, RasterId raster);

    /// Свободный растр под переворот: его не носит ни страница, ни осевший
    /// разворот, ни летящие листы — о них знает `held(raster)`. Свободного нет
    /// — заводится новый, в нынешней мере.
    template <class Held>
    RasterId acquireRaster(const Held& held) {
        for (RasterId raster = 0; raster < rasters_.size(); ++raster)
            if (spare(raster, held)) return raster;
        return addRaster();
    }

    /// Сколько свободных растров держит пул.
    template <class Held>
    size_t spareRasters(const Held& held) const {
        size_t count = 0;
        for (RasterId raster = 0; raster < rasters_.size(); ++raster)
            if (spare(raster, held)) ++count;
        return count;
    }

    /// Отпускает один свободный растр — последний: с ним уходит поверхность в
    /// размер окна. Кисть растра держат только те, кто его носит, — страницы
    /// и летящие листы; у свободного их нет, и поверхность не переживает его
    /// ничьей кистью. Номера остальных не двигаются.
    template <class Held>
    void dropSpareRaster(const Held& held) {
        for (RasterId raster = static_cast<RasterId>(rasters_.size()); raster-- > 0;)
            if (spare(raster, held)) {
                rasters_[raster].reset();
                return;
            }
    }

    /// Отпускает все свободные растры, когда летящих листов нет вовсе: у
    /// переворота без анимации их не бывает, и растр ему нужен один — осевший.
    void dropSpareRasters();

private:
    /// Носят ли растр страницы или осевший разворот.
    bool worn(RasterId raster) const;

    template <class Held>
    bool spare(RasterId raster, const Held& held) const {
        return rasters_[raster].has_value() && !worn(raster) && !held(raster);
    }

    /// Новый растр в нынешней мере — на место отпущенного, если такое есть.
    RasterId addRaster();

    wxl::Compositor compositor_;
    Painter painter_;

    /// Две страницы разворота — два визуала на сцене окна, левая и правая
    /// половины окна. Каждая носит кисть растра того разворота, что
    /// показывает: в покое обе — осевший; в книжном листании перелистываемая с
    /// первого кадра одета в новый разворот (из-под снимаемой бумаги
    /// открывается новая страница), другая остаётся на старом, пока приходящий
    /// лист её не накроет, и переезжает на разворот каждого севшего листа.
    /// Задник окна в чтении без кисти: страницы кроют его целиком, красить под
    /// ними нечего. Размер и шов берут у сцены выражениями композитора, потому
    /// идут за окном синхронно с WM_SIZE — resize их не трогает.
    wxl::SpriteVisual leftPageVisual_;
    wxl::SpriteVisual rightPageVisual_;

    /// Какой растр носит каждая страница: левая, правая.
    std::array<RasterId, 2> pageRasters_{kNoRaster, kNoRaster};

    /// Пул растров разворота (DrawingSurface без пустого конструктора — в
    /// optional). Пустое место — отпущенный растр: номера живых не двигаются,
    /// а новый встанет на его место.
    std::vector<std::optional<wxl::DrawingSurface>> rasters_;

    RasterId settledRaster_ = kNoRaster;
    wxl::SizeInt32 pixels_{};
    bool shown_ = false;
};

}  // namespace bukvitsa::reader
