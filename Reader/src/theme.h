#pragma once
// Оформление полосы: четыре встроенные темы, а за ними — обложки читателя.
//
// Цвета подобраны так, чтобы контраст текста к фону был ниже, чем чёрное по
// белому: страница бумажной книги отражает от 70 до 85 процентов света, а не
// сто, и глаз к этому привык. Чистый белый фон на экране читается как лист,
// подсвеченный изнутри, — от него устают.
//
// Цвета сразу в том виде, в каком их берёт Direct2D: полосу рисуем мы сами, и
// переводить их по дороге незачем.

#include <string_view>

#include <d2d1.h>

namespace bukvitsa::reader {

struct Theme {
    const wchar_t* name;   ///< подпись в панели, по-русски

    /// Имя темы в настройках: `Day`, `Sepia`, `Night`. Ключ, а не подпись, и
    /// потому не переводится и не меняется.
    ///
    /// Раньше настройки помнили тему номером — и номер поплыл, как только
    /// «Антиквариат» ушёл из тем в обложки: всё, что стояло за ним, сдвинулось
    /// на единицу, и файл, записанный вчера, сегодня значил бы другое. Номер
    /// остаётся внутри полосы, где им адресуют общий список «темы, затем
    /// обложки», — но на диск уходит имя.
    ///
    /// У палитры обложки (`kSkinTheme`) ключа нет: в настройках она не
    /// пишется, там стоит имя самой обложки.
    const wchar_t* id;
    D2D1_COLOR_F background;
    D2D1_COLOR_F text;
    D2D1_COLOR_F dim;      ///< колонцифра и прогресс — тише основного текста
    D2D1_COLOR_F panel;    ///< подложка сноски и панели: чуть иначе, чем полоса

    /// Цвет теней: средника, сгиба, поднятой бумаги. Коричневый, а не чёрный —
    /// бумага не отражает свет ровно, и тень на ней уходит в тон самой бумаги,
    /// а не в серое. Прозрачность у каждой тени своя, здесь только тон.
    ///
    /// Сдвинут в сторону сепии против прежнего, почти чёрного. Тот был выбран
    /// так, чтобы тепло читалось разницей каналов и не давало бурого налёта, —
    /// но у корешка, где тень гуще всего, он выглядел провалом в чёрное, а не
    /// углублением бумаги. Теперь тон светлее и теплее, и вместе с ослабленной
    /// плотностью (kFoldNear в book_view.cpp) корешок уходит вглубь сепией.
    ///
    /// Цвет в теме, а не общей константой, из-за ночной полосы. Там затемнять
    /// в бумаге нечего, она и так почти чёрная, — тень работает на буквах.
    /// Сепия, годная дневной странице, легла бы по такой бумаге бурой дымкой:
    /// она её светлее. Ночной тон поэтому остаётся темнее полосы, а тёплый он
    /// перевесом красного над синим — как и остальные три.
    D2D1_COLOR_F shadow;

};

/// Из восьмибитного цвета, каким его удобно записывать, в тот, каким его
/// хочет D2D. constexpr, поэтому таблица ниже остаётся таблицей.
constexpr D2D1_COLOR_F rgb(int r, int g, int b) {
    return {r / 255.0f, g / 255.0f, b / 255.0f, 1.0f};
}

/// Темы — это три ровных цвета, и фотографии среди них нет ни одной.
///
/// Раньше четвёртой стоял «Антиквариат» — тема с фотографией старой книги, —
/// и он был единственным, ради чего у темы было поле «подложка». Теперь он
/// обложка, первая из системных (skins.h): у обложки есть то, чего у темы не
/// было и быть не могло, — свои кривые краёв, снятые с её же снимка. Так
/// исчезло и деление «тема с картинкой против темы без картинки»: картинку
/// носит обложка, цвет — тема.
inline constexpr Theme kThemes[] = {
    {L"День",  L"Day",   rgb(250, 248, 243), rgb(32, 30, 28),    rgb(150, 145, 138),
     rgb(236, 232, 224), rgb(76, 52, 26)},
    {L"Сепия", L"Sepia", rgb(245, 233, 209), rgb(70, 52, 32),    rgb(160, 138, 106),
     rgb(232, 216, 186), rgb(92, 62, 28)},
    {L"Ночь",  L"Night", rgb(24, 24, 26),    rgb(208, 204, 198), rgb(110, 108, 104),
     rgb(40, 40, 44),    rgb(10, 6, 2)},
};

inline constexpr int kThemeCount = static_cast<int>(sizeof(kThemes) / sizeof(kThemes[0]));

/// Палитра, которую носит любая обложка: снимок и кривые у каждой свои, а
/// цвета — текста, колонцифры, сноски, теней — общие. Это прежние цвета
/// «Антиквариата», подобранные под страницы старой книги на фотографии:
/// `background` — тон её бумаги, чтобы полоса до загрузки снимка и подложка
/// XAML под поверхностью не отличались от него вспышкой.
inline constexpr Theme kSkinTheme{L"Обложка",        nullptr,            rgb(238, 221, 184),
                                  rgb(54, 38, 22),   rgb(158, 132, 96),  rgb(230, 210, 172),
                                  rgb(88, 58, 26)};

/// Номер темы по её имени из настроек. Незнакомое имя — первая тема: файл
/// могли принести с машины, где тем было другое число, или поправить руками, и
/// это не повод открыться иначе, чем открывается новая читалка.
inline int themeById(std::wstring_view id) {
    for (int index = 0; index < kThemeCount; ++index) {
        if (id == kThemes[index].id) return index;
    }

    return 0;
}

/// Имя темы для настроек. Номер вне списка значит, что выбрана обложка, а не
/// тема; именем тогда отвечает первая — настройки помнят её как то, куда
/// вернуться, когда обложки не станет.
inline const wchar_t* themeIdAt(int index) {
    return kThemes[index >= 0 && index < kThemeCount ? index : 0].id;
}

}  // namespace bukvitsa::reader
