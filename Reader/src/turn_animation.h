#pragma once
// TurnAnimation — как выглядит переворот, отдельно от того, что он делает.
//
// Что делает переворот, одинаково всегда, и это ведущего полосы
// (`BookPresenter`): книга шагает на разворот, разворот рисуется туда, где он
// теперь живёт, место чтения сдвигается. Порядок этих шагов — инвариант, а не
// вкус анимации: уходящий разворот берётся до шага книги, новый рисуется
// после, и только потом что-нибудь начинает двигаться. Стратегия зовётся в
// двух точках этого порядка — до шага и после отрисовки нового разворота
// (полоса передаёт ей просьбы ведущего к холсту) — и решает только то, как
// переворот выглядит: лист в воздухе или ничего.
//
// Две реализации: «листы» (`LeafTurnAnimation`) и «без анимации» — ниже.
// Полоса выбирает по настройке читателя и меняет на ходу: прежняя сперва
// доводит всё, что летит, до конечного состояния (finishAll), потом её
// заменяют.
//
// Владение: стратегией владеет полоса; разворот, который она видит, — полосы.

#include "pch.h"

#include "spread_view.h"

namespace bukvitsa::reader {

/// Анимация переворота: две точки в порядке шагов полосы, конечное состояние
/// всего, что летит, и то, куда рисовать нынешний разворот.
class TurnAnimation {
public:
    virtual ~TurnAnimation() = default;

    /// До шага книги: страницы ещё на старом развороте. Встречное листание
    /// здесь сперва доводит до конца всё, что летит (finishAll), — бумага
    /// снимается только с осевшего разворота.
    virtual void turnStarting(bool forward) = 0;

    /// После шага книги и отрисовки нового разворота в drawTarget(): лист
    /// берёт, что ему положено, и пускается в полёт.
    virtual void turnStarted(bool forward) = 0;

    /// Всё, что летит, — в конечное состояние, синхронно: на нём следующей
    /// строкой стоят встречное листание, перевёрстка, прыжок, новая мера,
    /// возврат в чтение и смена самой стратегии.
    virtual void finishAll() = 0;

    /// Куда рисовать нынешний разворот: в полёте книжного листа — его растр,
    /// иначе осевший.
    virtual SpreadView::RasterId drawTarget() const = 0;

    /// Тени переворота — тоном этой темы.
    virtual void tintShadows(const D2D1_COLOR_F& shadowHue) = 0;
};

/// Переворот без анимации: разворот сменяется разом. Полоса и так делает всё,
/// что такой переворот значит, — шаг книги, отрисовку в осевший растр и
/// одевание страниц, место чтения, — и стратегии добавить нечего: в воздухе
/// ничего нет, конечное состояние наступает сразу, растр нужен один.
class InstantTurnAnimation final : public TurnAnimation {
public:
    explicit InstantTurnAnimation(const SpreadView& spreadView) : spreadView_(spreadView) {}

    void turnStarting(bool) override {}
    void turnStarted(bool) override {}
    void finishAll() override {}
    SpreadView::RasterId drawTarget() const override { return spreadView_.settledRaster(); }
    void tintShadows(const D2D1_COLOR_F&) override {}

private:
    const SpreadView& spreadView_;
};

}  // namespace bukvitsa::reader
