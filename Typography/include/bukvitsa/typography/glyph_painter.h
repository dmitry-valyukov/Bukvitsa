#pragma once
// Отрисовка того, что навёрстано: прогон глифов и строка целиком.
//
// Живёт в Typography, а не в приложении, потому что перевод прогона глифов в
// вызов Direct2D — вторая половина той же работы: кто разложил глифы по
// строке, тот и знает, как их нарисовать. Приложениям остаётся решить, где и
// каким цветом, а это уже не сюда.
//
// Кисти и контекст приходят снаружи, и откуда они взялись — не наше дело:
// ни полей, ни тем, ни решений о том, что показывать, здесь нет. Кисть — на
// каждую роль прогона (TextRole), и какую взять, знает прогон: роль едет в его
// стиле от разметки книги. Это и держит границу слоёв: D2D — API отрисовки
// того же уровня, что DirectWrite, которую Typography и так знает, а вот окна
// и темы ей по-прежнему неизвестны.

// Через layout.h, а тот — через block.h: там собрано объединение стандартных
// заголовков всех публичных заголовков вёрстки и стоит импорт, после которого
// стандартный заголовок MSVC уже не примет.
#include "bukvitsa/typography/layout.h"

namespace bukvitsa::typography {

/// Кисти вывода по ролям прогона: чем набран текст книги и чем — знаки сносок.
/// Заёмные: кисти живут у того, кто рисует, и переживают отрисовку. Две роли —
/// два поля, а не таблица: новая роль добавит поле и ветку в brushFor, и
/// компилятор покажет каждого, кто кистей ей не дал.
struct TextBrushes {
    not_null<ID2D1Brush> body;
    not_null<ID2D1Brush> noteMark;

    /// Кисть прогона этой роли.
    not_null<ID2D1Brush> brushFor(TextRole role) const;
};

/// Рисует прогон глифов кистью его роли; x — левый край прогона, baseline —
/// базовая линия.
///
/// Подчёркивание и зачёркивание чертятся здесь же по метрикам шрифта и той же
/// кистью, что глифы: в самом шрифте их нет, а место и толщину знает только
/// он.
void drawGlyphRun(ID2D1DeviceContext* context, const GlyphRun& run, float x, float baseline,
                  const TextBrushes& brushes);

/// Рисует строку целиком: originX прогонов отсчитывается от x, каждый прогон —
/// кистью своей роли.
void drawLine(ID2D1DeviceContext* context, const Line& line, float x, float baseline,
              const TextBrushes& brushes);

}  // namespace bukvitsa::typography
