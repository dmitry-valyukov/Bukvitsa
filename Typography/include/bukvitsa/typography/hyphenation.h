#pragma once
// Переносы: где длинное слово можно разорвать по слогам.
//
// Без переносов выключенный русский текст набирается дырами: разбивке абзаца
// (linebreak.h) просто нечего выбирать, когда следующее слово вдвое длиннее
// остатка строки. Перенос даёт ей это место — флагированным штрафом, цена
// которого равна ширине дефиса.
//
// Размечает слово алгоритм Лянга, тот же, что в TeX: таблица образцов вида
// «встретив „абр“, разреши разрыв между „а“ и „б“», сложенная в бор и
// склеенная до графа. Таблицу собирает Typography/tools/gen-hyphen-patterns.py
// из образцов hyph-utf8, и она компилируется в двоичный файл — со словарём на
// диске читалка ждала бы его чтения на первой же странице.
//
// Почему не правила «гласная + согласная + гласная», которых хватило бы на
// сотню строк: русский перенос морфологичен, и такие правила ошибаются ровно
// там, где читатель это видит, — «по-дъезд» вместо «подъ-езд», «ра-збить»
// вместо «раз-бить», «ва-нна» вместо «ван-на». Образцы Лянга собраны по
// словарю и таких ошибок не делают.
//
// Считается один раз на абзац, при шейпинге: места переноса не зависят ни от
// кегля, ни от ширины полосы, а значит переживают и смену окна, и смену
// шрифта.

// Своих стандартных заголовков нет — они взяты из block.h, где собрано
// объединение нужного всем публичным заголовкам вёрстки: после импорта модуля
// MSVC стандартный заголовок уже не принимает, и порядок включения перестал бы
// быть свободным.
#include "bukvitsa/typography/block.h"

namespace bukvitsa::typography {

/// Слово длиннее этого не переносится: маска мест не поместилась бы в слово
/// машины, а текст, где такие слова есть, переносами всё равно не спасти.
inline constexpr std::size_t kMaxHyphenatedWord = 62;

/// Места переноса внутри слова: бит `i` значит «перед `i`-м символом слова
/// разрыв возможен», то есть на строке останется ровно `i` первых символов.
/// Ноль — переносить нельзя нигде.
using HyphenPoints = std::uint64_t;

/// Где слово можно разорвать переносом.
///
/// Язык берётся по письменности самого слова, а не по языку книги: книги почти
/// всегда смешанные, и латинское слово в русском тексте должно переноситься по
/// английским образцам, а не по русским.
///
/// Кодовая точка вне алфавита образцов — цифра, дефис, надстрочный знак,
/// эмодзи, буква третьей письменности — отменяет перенос всего слова. Это не
/// осторожность, а то, отчего закон цельности буквы соблюдается сам: разорвать
/// можно только слово из одних букв алфавита, а там нет ни составных знаков,
/// ни суррогатных пар, ни лигатур, которые разрыв мог бы разрушить.
///
/// Минимум букв, остающихся на строке и уходящих на следующую, объявлен в
/// самих образцах (русские требуют 2 и 2, английские 2 и 3) и применён здесь:
/// одну букву не оставляют и не переносят.
///
/// @param word одно слово, без пробелов по краям и внутри.
HyphenPoints hyphenate(std::wstring_view word) noexcept;

/// Буква, которую образцы знают, — по таким границам текст и делится на слова
/// перед разметкой. Знак препинания буквой не считается, и «слова,» приходит
/// сюда без запятой; дефис — тоже, и «тёмно-синий» размечается половинами,
/// как он и переносится.
bool isHyphenLetter(wchar_t character) noexcept;

}  // namespace bukvitsa::typography
