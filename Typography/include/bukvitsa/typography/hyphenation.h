#pragma once
// Переносы: где длинное слово можно разорвать по слогам.
//
// Без переносов русский текст, выключенный по формату, набирается дырами:
// разбивке абзаца (linebreak.h) просто нечего выбирать, когда следующее слово
// вдвое длиннее остатка строки. Перенос даёт ей это место — флагированным
// штрафом, цена которого равна ширине дефиса.
//
// Размечает слово алгоритм Лянга, тот же, что в TeX: таблица образцов вида
// «встретив „абр“, разреши разрыв между „а“ и „б“», сложенная в бор и
// склеенная до графа. Таблицу собирает Typography/tools/gen-hyphen-patterns.py
// из образцов hyph-utf8, и она компилируется в двоичный файл — со словарём на
// диске читалка ждала бы его чтения на первой же странице.
//
// Почему не правила «гласная + согласная + гласная», которых хватило бы на
// сотню строк: русский перенос морфологичен, и такие правила ошибаются ровно
// там, где читатель это видит, — «по-дъезд» вместо «подъ-езд», «ра-збить»
// вместо «раз-бить», «ва-нна» вместо «ван-на». Образцы Лянга собраны по
// словарю и таких ошибок не делают.
//
// Считается один раз на абзац, при шейпинге: места переноса не зависят ни от
// кегля, ни от ширины полосы, а значит переживают и смену окна, и смену
// шрифта.

// Своих стандартных заголовков нет — они взяты из block.h, где собрано
// объединение нужного всем публичным заголовкам вёрстки: после импорта модуля
// MSVC стандартный заголовок уже не принимает, и порядок включения перестал бы
// быть свободным.
#include "bukvitsa/typography/block.h"

namespace bukvitsa::typography {

/// Слово длиннее этого не переносится: маска мест не поместилась бы в слово
/// машины, а текст, где такие слова есть, переносами всё равно не спасти.
/// Считаются буквы: знаки ударения над ними в длину не входят.
inline constexpr size_t kMaxHyphenatedWord = 62;

/// Места переноса внутри слова: бит `i` значит «перед `i`-й единицей UTF-16
/// слова разрыв возможен», то есть на строке останется ровно `i` первых единиц.
/// Ноль — переносить нельзя нигде. Единица здесь всегда целая буква: разметку
/// получает только слово из букв алфавита образцов, а они все в BMP.
using HyphenPoints = uint64_t;

/// Где слово можно разорвать переносом — по одним образцам, без правил набора
/// (они — у hyphenPointsOf). Таким его и сверяют с эталоном: тот считает
/// образцы и ничего больше.
///
/// Язык берётся по письменности самого слова, а не по языку книги: книги почти
/// всегда смешанные, и латинское слово в русском тексте должно переноситься по
/// английским образцам, а не по русским.
///
/// Кодовая точка вне алфавита образцов — цифра, надстрочный знак, эмодзи,
/// буква третьей письменности — отменяет перенос всего слова: разметить можно
/// только слово из букв алфавита, а в нём нет ни составных знаков, ни
/// суррогатных пар, и разрыв между единицами — всегда разрыв между буквами.
/// Точка и дефис в алфавит образцов входят: русские образцы ими пишут край
/// слова и составное слово, и «северо-западный» здесь размечается целиком.
/// hyphenPointsOf их сюда не передаёт — у него дефис делит слово на части.
///
/// Минимум букв, остающихся на строке и уходящих на следующую, объявлен в
/// самих образцах (русские требуют 2 и 2, английские 2 и 3) и применён здесь:
/// одну букву не оставляют и не переносят.
///
/// @param word одно слово, без пробелов по краям и внутри, — кусок
///        проверенного текста абзаца.
HyphenPoints hyphenate(u16_view word) noexcept;

/// Места переноса во всём абзаце — то, что получает разбивка: байт на единицу
/// UTF-16 текста. Ноль — автоматического переноса перед этой единицей нет;
/// иначе это число букв части слова, которые перенос унесёт на следующую
/// строку, — по нему разбивка дороже берёт перенос с коротким хвостом.
///
/// Образцы знают, где слово рвать можно; какое слово рвать вовсе и какое из
/// найденных мест годится — правила набора, и они здесь:
///
/// - Слово — подряд идущие буквы, их знаки и то, что стоит внутри слов: цифры,
///   точка, дефис, апостроф, мягкий перенос. Кончается оно пробелом и
///   пунктуацией, а точка, дефис и апостроф на его краях — тоже пунктуация:
///   «слово.» — это «слово», «т.е.» — «т.е».
/// - Слово с цифрой, с точкой внутри или с буквой, которой образцы не знают,
///   не переносится вовсе: «страница5», «т.е.», «Ўзбекистон», «Übersetzung»
///   — это номера, сокращения и слова другого языка, и образцы русского и
///   английского о них ничего не знают. Чужая буква — буква любой
///   письменности, в BMP и вне его («Muḥammad», «Nguyễn»): до U+052F
///   буквы узнаются по общей категории Юникода, выше — буквой считается
///   всё, кроме блоков пробелов, пунктуации и символов, которые перечисляет
///   генератор таблицы. Поэтому буква из такого блока (ℓ, ⁿ) слово кончает,
///   как символ, а знак препинания чужой письменности вплотную к слову
///   отменяет его перенос, как буква.
/// - Дефис и апостроф делят слово на части, и каждая размечается сама:
///   «Петропавловск-Камчатский» — две части, и рвать можно в обеих. Разрыв
///   на самом дефисе даёт разбивка строк, здесь его нет.
/// - Часть, где заглавная стоит не первой буквой, не переносится: «ЮНЕСКО»,
///   «МосКва», «iPhone» — аббревиатура или имя собственное, которого образцы
///   не видели. Заглавная первой буквой — норма. Не переносится и часть, где
///   латиница и кириллица вперемешку: образцы одного языка к буквам другого
///   не применяются.
/// - В части с мягким переносом рвать можно только там, где он стоит:
///   поставив его, автор сказал, где слово рвётся, и места по образцам с ним
///   не смешиваются. Так велит и CSS Text Level 3 для `hyphens: auto`: в
///   слове с условным переносом автоматические места не ставятся, остаются
///   его. Сами эти места отдаёт разбивке DirectWrite, здесь их нет.
/// - Место, после которого с одной из сторон в части не остаётся гласной,
///   отбрасывается: «чк-нуть» не перенос, а обрубок.
/// - Знак ударения (U+0301, U+0300 — «досто́примечательность») не мешает:
///   образцы видят основу, а найденное место встаёт на границу буквы целиком,
///   перед её основой, — между основой и её знаком разрыва нет. Буква с
///   другим знаком («и» с краткой, «е» с диерезисом) — буква другая, образцам
///   незнакомая, и слово с ней не переносится. Знак без основы — после мягкого
///   переноса, в начале абзаца — слову не мешает.
///
/// @param notes знаки сносок абзаца. Знак — слово сам по себе: цифра сноски
///        вплотную к слову («маркизу5») слово не продолжает и его перенос не
///        отменяет.
sta_vector<uint8_t> hyphenPointsOf(u16_view paragraph, std::span<const NoteAnchor> notes);

}  // namespace bukvitsa::typography
