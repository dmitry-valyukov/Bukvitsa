#pragma once
// Сноска, разложенная по строкам для показа поверх страницы.
//
// Набор сноски — вёрстка, а не окно: тот же движок, что у книги, и свои
// правила — мельче, без абзацного отступа, с отбивкой между абзацами. Тому,
// кто её показывает, остаётся решить, где встать и каким цветом рисовать.
//
// Страниц у сноски нет: она набирается одной колонкой, а не поместившись —
// прокручивается. Поэтому раскладка отдельная от `Chapter` и сама владеет
// строками: в отличие от `PlacedLine`, указывать здесь не во что.
//
// Владение: прогоны глифов ссылаются на шрифты движка, так что раскладку
// нельзя пережить движком — как и любые строки (layout.h).

// Через layout.h, а тот — через block.h: там собрано объединение стандартных
// заголовков всех публичных заголовков вёрстки и стоит импорт, после которого
// стандартный заголовок MSVC уже не примет.
#include "bukvitsa/typography/layout.h"

namespace bukvitsa::typography {

/// Строка сноски на своей базовой линии. Левый край у всех строк — ноль:
/// втяжек в сноске нет.
struct NoteLine {
    Line line;
    float baseline = 0.0f;   ///< от верха сноски вниз
};

/// Тело сноски, разложенное по строкам.
struct NoteLayout {
    sta_vector<NoteLine> lines;   ///< сверху вниз
    float height = 0.0f;          ///< высота сноски с отбивкой после каждого абзаца, и последнего тоже
};

/// Верстает тело сноски в колонку шириной `width`.
///
/// @param engine   движок книги: его шрифты и его стиль текста.
/// @param note     тело сноски — узел, на который указывает `NoteAnchor::target`.
/// @param width    ширина колонки, DIP.
/// @param fontSize кегль книги; сноска набирается от него мельче.
/// @return ни одной строки и нулевая высота, если текста в сноске нет или
///         колонке нет ширины.
NoteLayout layoutNote(Engine& engine, const fb3::Node& note, float width, float fontSize);

}  // namespace bukvitsa::typography
