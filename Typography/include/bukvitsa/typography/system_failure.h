#pragma once
// Отказ системного вызова, на который у программы нет ответа, — остановка на
// месте отказа.
//
// Так отвечают Direct2D и DirectWrite при рисовании, системные фабрики
// (Direct2D, DirectWrite, WIC), поток памяти WIC, COM-диалог выбора файла,
// выдача guid и каталога данных: отказать они могут лишь от нехватки памяти,
// потери устройства или ошибки в коде — продолжать нечем, а страница или
// выбор, молча оставшиеся пустыми, были бы сбоем без имени. Остановка —
// `core::abort` с текстом «что не вышло, HRESULT 0x…» и строкой вызова:
// отладчик встаёт там, текст и место уходят в stderr и в отладчик, и путь
// один, кто бы ни звал.
//
// Потеря устройства — не отказ: Direct2D отвечает ею любому вызову посреди
// рисунка (кисть, слой, эффект, битмап, EndDraw своего контекста), и ответ
// на неё — «рисунок пропущен», а устройство заменят и всё нарисуют заново.
// Какие коды её называют и потеряно ли устройство на деле, знает тот, кто
// его заменяет, — wxl, а вёрстка о wxl.ui не знает. Поэтому здесь — точка
// расширения: проверку ставит читалка при запуске (setDeviceLossCheck), и
// stopIfFailed зовёт её у всякого отказа до остановки. Потеря — проверка
// бросает исключение wxl, его ловит рисунок поверхности; вне рисунка ловить
// некому — terminate, и обработчик wxl его называет. Код потери от целого
// устройства проверка останавливает сама. Не поставлена (пробы библиотеки)
// — отказ останавливает, как всякий.
//
// Отказ вызова, у которого нет устройства, идёт своей ступенью
// (stopIfFailedOffDevice): остановка та же, но без проверки — проверка
// спрашивает устройство, а это код потока, который рисует, тогда как такой
// вызов может прийти с любого потока.
//
// Отказы вёрстки на DirectWrite (engine.cpp) этим путём не идут — они
// бросают, как бросали. Чужие байты — картинка, которую не раскодировать, —
// тоже не сюда: это ответ о файле, а не отказ системы.
//
// Живёт в вёрстке, а не выше: она — нижний слой, который зовёт Direct2D
// (formula.cpp рисует), и её заголовки берут и модель, и читалка. Импорта
// здесь нет — текст остановки собирается в system_failure.cpp, — так что
// порядок включения ему безразличен; HRESULT приходит с windows.h общего
// pch.h.

#include <source_location>
#include <string_view>

namespace bukvitsa::typography {

/// Проверка отказа на потерю устройства: потеряно — бросает, иначе
/// возвращается. Голый указатель: ставится один раз, на всю жизнь процесса.
using DeviceLossCheck = void (*)(HRESULT result);

/// Ставит проверку — один раз, до первого рисунка; второй раз — остановка.
void setDeviceLossCheck(DeviceLossCheck check) noexcept;

namespace detail {

/// Отказ: проверка на потерю устройства (может бросить), затем остановка с
/// текстом «what, HRESULT 0x…» на месте `where`. Отдельно и не встроенной:
/// проверка на каждом вызове — одно сравнение, а всё прочее — только на пути
/// отказа.
[[noreturn]] void failed(HRESULT result, std::string_view what, std::source_location where);

/// Отказ вне устройства: сразу остановка, без проверки на потерю.
[[noreturn]] void failedOffDevice(HRESULT result, std::string_view what, std::source_location where) noexcept;

}  // namespace detail

/// Не удался вызов — остановка (`core::abort`) со словами и строкой вызова;
/// отказ потерянного устройства — исключение проверки (см. выше), поэтому не
/// noexcept.
/// @param what что не вышло и у кого: «BookView: не создалась кисть текста».
inline void stopIfFailed(HRESULT result, std::string_view what,
                         std::source_location where = std::source_location::current()) {
    if (FAILED(result)) [[unlikely]]
        detail::failed(result, what, where);
}

/// Не удался вызов, у которого нет устройства, — остановка, как у
/// stopIfFailed, но без проверки на потерю устройства; зовётся с любого
/// потока.
inline void stopIfFailedOffDevice(HRESULT result, std::string_view what,
                                  std::source_location where = std::source_location::current()) noexcept {
    if (FAILED(result)) [[unlikely]]
        detail::failedOffDevice(result, what, where);
}

}  // namespace bukvitsa::typography
