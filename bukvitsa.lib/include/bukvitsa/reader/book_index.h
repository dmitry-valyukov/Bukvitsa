#pragma once
// Два способа найти в книге место: оглавление и поиск.
//
// Оба стоят на блоках, в которые вёрстка развернула книгу, и оба отдают одно
// и то же — позицию в символах. Дальше её принимает полоса набора, которая
// умеет спросить у пагинатора номер страницы; ни оглавление, ни поиск про
// страницы не знают вовсе и потому не портятся от смены кегля.
//
// Почему по блокам, а не по дереву книги: блоки уже есть, в них текст сплошной
// (свёртка пробелов сделана), а рядом с каждым символом лежит его позиция в
// книге. Обходить дерево заново значило бы повторить эту работу и получить
// другие индексы.
//
// Зовут их из потока окна, и результат живёт в списках панели, пока открыта
// книга (`BookPlaces`, `BookSearch`), — поэтому списки берут память из
// STA-пула.

#include <cstdint>
#include <optional>
#include <span>
#include <string_view>

#include "bukvitsa/typography/block.h"

namespace bukvitsa::reader {

/// Строка оглавления.
///
/// Сравнения у неё нет намеренно: заголовок — вид в текст книги, и две книги с
/// одинаковыми заголовками дали бы равные строки. Список оглавления молчал бы
/// на замене книги и держал бы виды в блоки прежней.
struct ContentsEntry {
    u16_view title;        ///< вид в текст блока: живёт, пока живы блоки
    uint8_t level = 0;     ///< глубина секции: 0 — часть, дальше главы
    uint32_t charOffset = 0;
};

/// Оглавление книги: заголовки в порядке чтения.
///
/// Книга без заголовков бывает — тогда оглавление пустое, и показывать нечего.
/// Выдумывать вместо него список абзацев не нужно: пустое оглавление честнее
/// длинного списка ни о чём.
sta_vector<ContentsEntry> contentsOf(std::span<const typography::Block> blocks);

/// Находка поиска: место и кусок текста вокруг него.
struct SearchHit {
    u16_text context;         ///< отрывок абзаца, в котором нашлось
    uint32_t charOffset = 0;  ///< позиция самой находки в книге

    /// Находки сравнимы: список находок молчит, когда тот же поиск дал те же
    /// находки, и вид под ним не перестраивается зря.
    bool operator==(const SearchHit&) const = default;
};

/// Ищет по книге, не различая регистра.
///
/// @param limit сколько находок вернуть. Ограничение не от лени: «а» в романе
///        встречается десятки тысяч раз, и список из них бесполезен читателю
///        ровно так же, как дорог приложению.
sta_vector<SearchHit> searchBook(std::span<const typography::Block> blocks,
                                 u16_view needle, size_t limit = 200);

/// Запрос поиска из того, что набрал читатель: проверенный текст или пусто —
/// искать нечего.
///
/// Набранное — чужой текст: приходит из поля ввода строкой системы, и
/// одиночная половина суррогатной пары в нём возможна; такой запрос не
/// ищется. Пустой и из одних пробелов и табуляций — тоже: слова в нём нет.
/// Края не срезаются — ищется то, что набрано.
/// @return вид в `typed`: живёт, пока жива строка поля
std::optional<u16_view> searchQuery(std::u16string_view typed);

/// Первые слова абзаца, в котором стоит эта позиция, — подсказка для закладки.
u16_text hintAt(std::span<const typography::Block> blocks, uint32_t charOffset);

}  // namespace bukvitsa::reader
