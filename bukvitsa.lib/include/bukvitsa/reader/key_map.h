#pragma once
// Карта клавиш читалки: что значит клавиша — в зависимости от того, что на
// экране, что открыто поверх страницы и у какого элемента клавиша началась.
//
// Решение — чистая функция `resolve` без окон: Reader переводит клавишу WinUI
// в `KeyPress`, собирает `KeyContext` из своих экранов и исполняет ответ.
// На экране ошибку клавиш видно только драйвером окна и экранным диктором;
// решение, отделённое от исполнения, проверяет обычный тест.
//
// Матрица. Клавиша идёт туннелем от корня экрана к элементу в фокусе, и над
// книгой её первой видит полоса, а приложение — только то, что полоса не
// взяла. `resolve` повторяет этот порядок порядком правил.
//
// 1. Полоса — только над книгой (`Screen::Book`).
//    а) Клавиша началась у ползунка или поля ввода (`FocusOrigin::Slider`,
//       `FocusOrigin::TextBox`) — она их: стрелки, пробел, Home/End и буквы
//       полоса пропускает дальше, к п. 2, иначе ползунок с клавиатуры не
//       тронуть, а «т» в поиске меняла бы тему. PgUp/PgDn ни ползунок, ни
//       однострочное поле не читают — ими листают из любого фокуса. Кнопка и
//       корень по клавишам не ходят: из них полоса берёт всё своё.
//    б) Открыт мастер обложек: остаётся листание и Home/End — изгибы
//       подстраивают под конкретный текст, и ходить по книге нужно прямо из
//       мастера. Остальное идёт к п. 2, где под мастером всё молчит.
//    в) Иначе: листание (PgDn, →, ↓, пробел — вперёд; PgUp, ←, ↑ — назад),
//       Home/End — начало и конец книги, Ctrl с «+», «−», «0» (цифровой
//       клавиатуры и «0» верхнего ряда) — кегль; голая T — следующая тема,
//       Ctrl+T полосе не принадлежит (оглавление, п. 2). Без Ctrl «+», «−» и
//       «0» полоса берёт и ничего не делает.
//    Ctrl листания и Home/End не меняет. Home/End — только при открытой книге:
//    конец известен лишь ей.
// 2. Приложение — на любом экране, то, что полоса не взяла.
//    а) Открыт мастер — молчит всё: Escape увёл бы с полосы прямо под ним,
//       дороги из мастера — его кнопки.
//    б) Ctrl+L — полка отовсюду, из любого фокуса: выбрать другую книгу
//       читатель вправе в любой момент. На самой полке — ничего.
//    в) Над книгой Ctrl+T, Ctrl+F, Ctrl+B — оба ящика, левый на оглавлении,
//       поиске или закладках; Ctrl с прочим над книгой — ничего.
//    г) F2 — оба ящика, только над книгой: над заставкой и полкой им нечего
//       показывать. F11 — полный экран, везде.
//    д) Escape — один приоритет на всё приложение: панель → сноска (над
//       книгой) → полный экран → из книги туда, откуда её открыли (полка или
//       заставка) → с полки на заставку → ничего. Сперва убрать то, что лежит
//       поверх страницы, потом выйти из полного экрана, и лишь потом уйти с
//       экрана.

namespace bukvitsa::reader {

/// Что сейчас в окне. Три экрана, переход между ними — смена содержимого
/// окна. Мастер обложек — не экран, а оверлей поверх полосы: под ним читатель
/// видит свою страницу, изогнутую редактируемыми кривыми.
enum class Screen { Start, Library, Book };

/// Клавиши, которые что-то значат для читалки. Остальные — `Other`: карте
/// незачем знать всю клавиатуру, а Reader переводит в эти имена клавиши WinUI.
enum class Key {
    PageDown,
    PageUp,
    Right,
    Left,
    Down,
    Up,
    Space,
    Home,
    End,
    Add,          ///< «+» цифровой клавиатуры
    Subtract,     ///< «−» цифровой клавиатуры
    Number0,      ///< «0» верхнего ряда
    NumberPad0,   ///< «0» цифровой клавиатуры
    T,
    F,
    B,
    L,
    F2,
    F11,
    Escape,
    Other,
};

/// Нажатие: клавиша и зажат ли Ctrl. Других модификаторов читалка не слушает.
struct KeyPress {
    Key key = Key::Other;
    bool control = false;
};

/// У какого элемента началась клавиша. Ползунок и поле ввода ходят по
/// клавишам сами; кнопка и корень экрана — нет.
enum class FocusOrigin { Root, Button, Slider, TextBox };

/// Всё, от чего зависит смысл клавиши: экран, что открыто поверх, откуда
/// клавиша пришла.
struct KeyContext {
    Screen shown = Screen::Start;      ///< экран в окне
    Screen cameFrom = Screen::Start;   ///< откуда открыли книгу: туда её Escape
    bool wizardOpen = false;           ///< мастер обложек поверх полосы
    bool panelOpen = false;            ///< ящики панели
    bool noteOpen = false;             ///< всплывашка сноски
    bool fullScreen = false;
    FocusOrigin origin = FocusOrigin::Root;
    bool bookOpen = false;             ///< в полосе есть книга
};

/// Что сделать. `None` — клавиша не читалки: её не помечают обработанной, и
/// она идёт дальше, к элементу в фокусе.
enum class Command {
    None,
    TurnForward,
    TurnBackward,
    GoToStart,
    GoToEnd,
    FontLarger,
    FontSmaller,
    FontReset,
    NextTheme,
    ShowLibrary,
    OpenContents,
    OpenSearch,
    OpenBookmarks,
    TogglePanel,
    ToggleFullScreen,
    ClosePanel,
    DismissNote,
    LeaveFullScreen,
    BackToLibrary,   ///< из книги на полку, откуда её открыли
    BackToStart,     ///< на заставку: из книги, открытой с неё, или с полки
};

/// Смысл нажатия в этом контексте — по матрице в начале файла.
Command resolve(const KeyPress& press, const KeyContext& context);

}  // namespace bukvitsa::reader
