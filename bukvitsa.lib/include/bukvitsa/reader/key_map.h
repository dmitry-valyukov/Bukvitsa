#pragma once
// Карта клавиш читалки: что значит клавиша — в зависимости от того, что на
// экране, что открыто поверх страницы и у какого элемента клавиша началась, —
// а заодно колесо и щелчок по странице: они листают и меняют кегль так же, как
// клавиши, и решаться это должно в одном месте.
//
// Решение — чистые функции без окон (`resolve`, для мыши `resolveWheel` и
// `resolveTap`): Reader переводит событие WinUI в их аргументы, собирает
// `KeyContext` из своих экранов и исполняет ответ. На экране ошибку ввода видно
// только драйвером окна и экранным диктором; решение, отделённое от
// исполнения, проверяет обычный тест.
//
// Матрица. Над книгой у клавиши два хозяина — полоса (листание, кегль, тема) и
// приложение (экраны, ящики, Escape), — и правила полосы старше: приложению
// достаётся только то, что полоса не взяла. Порядок держат правила `resolve`, а
// не очерёдность обработчиков: над книгой обработчик один — у корня полосы, на
// пути вниз, раньше элемента в фокусе, — и он же исполняет ответ.
//
// 1. Полоса — только над книгой (`Screen::Book`).
//    а) Клавиша началась у ползунка или поля ввода (`FocusOrigin::Slider`,
//       `FocusOrigin::TextBox`) — она их: стрелки, пробел, Home/End и буквы
//       полоса пропускает дальше, к п. 2, иначе ползунок с клавиатуры не
//       тронуть, а «т» в поиске меняла бы тему. PgUp/PgDn ни ползунок, ни
//       однострочное поле не читают — ими листают из любого фокуса. Кнопка и
//       корень по клавишам не ходят: из них полоса берёт всё своё.
//    б) Открыт мастер обложек: остаётся листание и Home/End — изгибы
//       подстраивают под конкретный текст, и ходить по книге нужно прямо из
//       мастера. Остальное идёт к п. 2, где под мастером всё молчит.
//    в) Открыта сноска, поверх неё нет ни панели, ни мастера, и клавиша
//       началась у корня или кнопки: вертикальные клавиши — сноски, а не
//       книги. PgDn и пробел — на окно вниз, PgUp — на окно вверх, ↓ и ↑ —
//       на строку, Home/End — к началу и к концу сноски. Длинную сноску
//       иначе нечем прочесть с клавиатуры, а листание спрятало бы её вместе
//       со страницей. Короткой сноске и докрученной до края эти клавиши
//       ничего не делают, но и книге не уходят — как колесо, которое
//       всплывашка съедает: читатель смотрит на сноску, и страница под ней не
//       должна перевернуться оттого, что сноска кончилась. ← и → листают,
//       как и прежде, и, листая, сноску закрывают; Escape закрывает её
//       (п. 2д). Под панелью и мастером сноска не то, на что смотрят, —
//       клавиши как без неё; ползунок и поле ввода держат свои клавиши и
//       здесь (п. 1а).
//    г) Иначе: листание (PgDn, →, ↓, пробел — вперёд; PgUp, ←, ↑ — назад),
//       Home/End — начало и конец книги, Ctrl с «+», «−», «0» (цифровой
//       клавиатуры и «0» верхнего ряда) — кегль; голая T — следующая тема,
//       Ctrl+T полосе не принадлежит (оглавление, п. 2). Без Ctrl «+», «−» и
//       «0» не значат ничего.
//    Ctrl листания, прокрутки сноски и Home/End не меняет. Home/End книги —
//    только при открытой книге: конец известен лишь ей.
// 2. Приложение — на любом экране, то, что полоса не взяла.
//    а) Открыт мастер — молчит всё: Escape увёл бы с полосы прямо под ним,
//       дороги из мастера — его кнопки.
//    б) Ctrl+L — полка отовсюду, из любого фокуса: выбрать другую книгу
//       читатель вправе в любой момент. На самой полке — ничего.
//    в) Над книгой Ctrl+T, Ctrl+F, Ctrl+B — оба ящика, левый на оглавлении,
//       поиске или закладках; Ctrl с прочим над книгой — ничего.
//    г) F2 — оба ящика, только над книгой: над заставкой и полкой им нечего
//       показывать. F11 — полный экран, везде.
//    д) Escape — один приоритет на всё приложение: панель → сноска (над
//       книгой) → полный экран → из книги туда, откуда её открыли (полка или
//       заставка) → с полки на заставку → ничего. Сперва убрать то, что лежит
//       поверх страницы, потом выйти из полного экрана, и лишь потом уйти с
//       экрана.
// 3. Мышь над полосой (`resolveWheel`, `resolveTap`) — только над книгой: к
//    полосе мышь приходит, лишь пока она в окне.
//    а) Колесо листает: от себя — назад, на себя — вперёд, как прокрутка
//       ленты; с Ctrl — кегль, от себя — крупнее. Под мастером так же: изгиб
//       подстраивают под конкретный текст в конкретном виде. Хода нет —
//       ничего.
//    б) Щелчок по левой трети полосы — назад, по правой — вперёд; середина не
//       делает ничего: там текст, и промах по ссылке не должен листать. Правая
//       кнопка — оба ящика: другой дороги к ним у мыши нет, у страницы нет ни
//       меню, ни кнопок. Под мастером листает только левая кнопка, остальные
//       молчат: ящикам под мастером не место.
//    Знак сноски карте не принадлежит: попадание в него полоса проверяет
//    раньше, и тогда щелчок — сноска, а не листание; щелчок мимо знака при
//    открытой сноске закрывает её и тоже не листает.

namespace bukvitsa::reader {

/// Что сейчас в окне. Три экрана, переход между ними — смена содержимого
/// окна. Мастер обложек — не экран, а оверлей поверх полосы: под ним читатель
/// видит свою страницу, изогнутую редактируемыми кривыми.
enum class Screen { Start, Library, Book };

/// Клавиши, которые что-то значат для читалки. Остальные — `Other`: карте
/// незачем знать всю клавиатуру, а Reader переводит в эти имена клавиши WinUI.
enum class Key {
    PageDown,
    PageUp,
    Right,
    Left,
    Down,
    Up,
    Space,
    Home,
    End,
    Add,          ///< «+» цифровой клавиатуры
    Subtract,     ///< «−» цифровой клавиатуры
    Number0,      ///< «0» верхнего ряда
    NumberPad0,   ///< «0» цифровой клавиатуры
    T,
    F,
    B,
    L,
    F2,
    F11,
    Escape,
    Other,
};

/// Нажатие: клавиша и зажат ли Ctrl. Других модификаторов читалка не слушает.
struct KeyPress {
    Key key = Key::Other;
    bool control = false;
};

/// У какого элемента началась клавиша. Ползунок и поле ввода ходят по
/// клавишам сами; кнопка и корень экрана — нет.
enum class FocusOrigin { Root, Button, Slider, TextBox };

/// Всё, от чего зависит смысл клавиши: экран, что открыто поверх, откуда
/// клавиша пришла.
struct KeyContext {
    Screen shown = Screen::Start;      ///< экран в окне
    Screen cameFrom = Screen::Start;   ///< откуда открыли книгу: туда её Escape
    bool wizardOpen = false;           ///< мастер обложек поверх полосы
    bool panelOpen = false;            ///< ящики панели
    bool noteOpen = false;             ///< всплывашка сноски
    bool fullScreen = false;
    FocusOrigin origin = FocusOrigin::Root;
    bool bookOpen = false;             ///< в полосе есть книга
};

/// Что сделать. `None` — клавиша не читалки: её не помечают обработанной, и
/// она идёт дальше, к элементу в фокусе. Листание, начало и конец книги,
/// кегль, тему, прокрутку и закрытие сноски исполняет полоса, остальное —
/// приложение.
enum class Command {
    None,
    TurnForward,
    TurnBackward,
    GoToStart,
    GoToEnd,
    FontLarger,
    FontSmaller,
    FontReset,
    NextTheme,
    ShowLibrary,
    OpenContents,
    OpenSearch,
    OpenBookmarks,
    TogglePanel,
    ToggleFullScreen,
    ClosePanel,
    DismissNote,
    ScrollNoteLineDown,   ///< открытая сноска — на строку вниз
    ScrollNoteLineUp,     ///< на строку вверх
    ScrollNotePageDown,   ///< на окно вниз
    ScrollNotePageUp,     ///< на окно вверх
    ScrollNoteToStart,    ///< к началу сноски
    ScrollNoteToEnd,      ///< к концу сноски
    LeaveFullScreen,
    BackToLibrary,   ///< из книги на полку, откуда её открыли
    BackToStart,     ///< на заставку: из книги, открытой с неё, или с полки
};

/// Кнопка, которой щёлкнули по странице: левая, правая или иная — средняя,
/// боковая.
enum class PointerButton { Left, Right, Other };

/// Смысл нажатия в этом контексте — по матрице в начале файла.
Command resolve(const KeyPress& press, const KeyContext& context);

/// Смысл хода колеса над полосой (п. 3а матрицы). `delta` — ход колеса, от
/// себя — больше нуля; `control` — зажат ли Ctrl.
Command resolveWheel(int delta, bool control, const KeyContext& context);

/// Смысл щелчка по странице (п. 3б матрицы): `x` — где щёлкнули, `width` —
/// ширина полосы, в одних единицах. Попадание в знак сноски полоса проверяет
/// раньше: оно карте не принадлежит.
Command resolveTap(float x, float width, PointerButton button, const KeyContext& context);

}  // namespace bukvitsa::reader
