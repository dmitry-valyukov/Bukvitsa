#pragma once
// NoteBands — какие полосы тела сноски рисовать и какие держать.
//
// Сноска рисуется на виртуальной поверхности композитора
// (wxl::VirtualDrawingSurface) во весь свой рост, но пиксели есть только у
// нарисованного: устройство рисует за раз не больше одной своей текстуры без
// трёх пикселей, которые композиция берёт себе (16381 на сторону в лучшем
// случае), а комментарий в несколько тысяч слов при масштабе 1,5 выше её в
// разы. Поэтому тело режется решёткой полос по
// высоте, рисуются только полосы у окна прокрутки — с запасом в окно вперёд и
// окно назад, чтобы прокрутка не обгоняла рисунок, — а ушедшие дальше двух окон
// поверхность отдаёт обратно.
//
// Здесь — одна арифметика в пикселях поверхности, без окна: что дорисовать при
// показе и при движении прокрутки и что держать. Рисует и говорит поверхности,
// что оставить, всплывашка (NotePopup в Reader).
//
// Владение: решётка и отметки нарисованного — свои, по значению.

#include <cstdint>
#include <initializer_list>
#include <vector>

namespace bukvitsa::reader {

/// Прямоугольник в пикселях поверхности сноски: левый верхний угол и размер.
struct NotePixelRect {
    int32_t x = 0;
    int32_t y = 0;
    int32_t width = 0;
    int32_t height = 0;

    friend bool operator==(const NotePixelRect&, const NotePixelRect&) = default;
};

/// Мера решётки, все — в пикселях поверхности.
struct NoteBandsGeometry {
    int32_t surfaceWidth = 0;     ///< ширина поверхности сноски
    int32_t surfaceHeight = 0;    ///< рост сноски — поверхности
    int32_t viewportHeight = 0;   ///< высота окна прокрутки
    int32_t bandHeight = 0;       ///< желаемая высота полосы; выше maxUpdateSide режется до него
    int32_t maxUpdateSide = 0;    ///< предел стороны одного рисунка у устройства
};

/// Что сделать с поверхностью при этом виде.
struct NoteBandsStep {
    /// Куски, которые рисовать сейчас: ещё не нарисованные полосы у видов, по
    /// куску на полосу, а у поверхности шире предела устройства — по
    /// нескольку. Каждый кусок не длиннее maxUpdateSide по обеим сторонам.
    std::vector<NotePixelRect> drawRects;
    /// Что поверхность держит после шага: нарисованные полосы, идущие подряд,
    /// — одним прямоугольником во всю ширину, сверху вниз.
    std::vector<NotePixelRect> keepRects;
    /// Какая-то нарисованная полоса ушла от видов дальше двух окон и больше не
    /// держится — поверхности пора оставить только keepRects.
    bool trimNeeded = false;
};

class NoteBands {
public:
    /// Решётка для новой сноски или нового устройства: нарисованного нет.
    /// Отрицательная мера, полоса или предел не больше нуля — остановка: их
    /// считает всплывашка, и такое число — её ошибка, а не данные.
    void reset(const NoteBandsGeometry& geometry);

    /// Шаг для видов прокрутки — верхних краёв окна в пикселях поверхности:
    /// у всплывшей сноски вид один (начало), у движущейся прокрутки два —
    /// следующий кадр и место, где она встанет. У каждого вида рисуется окно и
    /// по окну вперёд и назад, держится — окно и по два окна в обе стороны;
    /// граница полосы — полуоткрытая: полоса, кончающаяся ровно там, где
    /// начинается окно, к нему не относится.
    ///
    /// Всё, что вернулось в drawRects, отмечается нарисованным: рисунок,
    /// пропущенный потерянным устройством, рисует заново замена устройства,
    /// начиная решётку с reset.
    NoteBandsStep advance(std::initializer_list<int32_t> viewTops);

    /// Высота полосы после предела устройства.
    int32_t bandHeight() const { return geometry_.bandHeight; }

    /// Полос в решётке: последняя бывает ниже прочих, пустой не бывает.
    int32_t bandCount() const { return static_cast<int32_t>(drawnBands_.size()); }

private:
    /// Полосы [first, last), задевающие отрезок [top, bottom) высоты сноски.
    struct BandRange {
        int32_t first = 0;
        int32_t last = 0;
    };
    BandRange bandsAcross(int64_t top, int64_t bottom) const;

    /// Куски полосы шириной не больше предела устройства, слева направо.
    void appendPieces(int32_t newBand, std::vector<NotePixelRect>& newPieces) const;

    NoteBandsGeometry geometry_;
    std::vector<bool> drawnBands_;   ///< по полосе: нарисована и держится
};

}  // namespace bukvitsa::reader
