#pragma once
// Мера всплывающей сноски: на какую колонку верстается её тело, какого роста
// всплывашка и какие у неё окно прокрутки и поверхность в пикселях экрана.
//
// Всплывашка — рамка (Border) вокруг окна прокрутки, в окне — подложка, на
// подложке — тело сноски с полем вокруг (NotePopup в Reader). Окно прокрутки
// режет всё, что за его краем, поэтому поле не у рамки, а внутри окна: срез
// приходится на край поля, а не на край колонки. Поле и вбирает всё, что
// выходит за колонку и чего вёрстка не мерит: чернила глифа за его шагом
// (курсивная прописная в конце строки, курсивное «р» в начале), округление
// разметки до пикселей и раскрытую полосу прокрутки, которая ложится поверх
// окна у его правого края.
//
// Разметка XAML округляет размер элемента и толщину рамки до целых пикселей
// экрана, к ближайшему, а поле — нет. Поэтому окно в пикселях — не «ширина без
// рамок», умноженная на масштаб: рамка в 1 DIP при масштабе 1,5 — два пикселя,
// а не полтора, и всплывашка ростом «подложка и две рамки» в DIP дала бы окно
// на пиксель ниже подложки — короткая сноска прокручивалась бы. Здесь эта
// арифметика одна, с масштабом и без окна; одевает, ставит и рисует
// всплывашка.

#include <cstdint>

namespace bukvitsa::reader {

/// Поле вокруг тела внутри окна прокрутки, DIP: по нему всплывашка отступает
/// от колонки до края окна.
inline constexpr float kNotePadding = 16.0f;

/// Толщина рамки всплывашки, DIP.
inline constexpr float kNoteBorder = 1.0f;

/// Колонка тела во всплывашке шириной popupWidth, DIP: всплывашка без двух
/// рамок и двух полей.
constexpr float noteColumn(float popupWidth) {
    return popupWidth - 2.0f * (kNoteBorder + kNotePadding);
}

/// Рост подложки под тело ростом bodyHeight, DIP: поле, тело, поле.
constexpr float notePaperHeight(float bodyHeight) {
    return bodyHeight + 2.0f * kNotePadding;
}

/// Сторона в DIP — в пикселях экрана с масштабом scale так, как её округляет
/// разметка XAML: к ближайшему целому, половина — вверх.
int32_t layoutPixels(float dips, float scale);

/// Всплывашка на экране: что задать разметке и что дать поверхности и решётке
/// полос.
struct NoteFrame {
    float popupHeight = 0.0f;   ///< рост всплывашки, DIP
    float paperHeight = 0.0f;   ///< рост подложки, DIP
    int32_t windowWidth = 0;    ///< ширина окна прокрутки, пиксели; она же — поверхности
    int32_t windowHeight = 0;   ///< высота окна прокрутки, пиксели
    int32_t paperPixels = 0;    ///< рост подложки, пиксели; он же — поверхности
};

/// Мера всплывашки шириной popupWidth над телом ростом bodyHeight на экране с
/// масштабом scale. Рост — тот, при котором окно прокрутки после округления
/// не ниже подложки, но не выше heightLimit: выше — тело прокручивается.
NoteFrame noteFrame(float popupWidth, float bodyHeight, float heightLimit, float scale);

}  // namespace bukvitsa::reader
