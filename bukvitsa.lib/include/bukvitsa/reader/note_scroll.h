#pragma once
// Прокрутка всплывающей сноски с клавиатуры: куда встать верху окна
// прокрутки, когда читатель просит строку, окно, начало или конец.
//
// Шаг ровно на высоту окна режет строки: строка, срезанная у нижнего края,
// после шага оказывается у верхнего своей нижней половиной, и читатель теряет
// то, чего не дочитал. Поэтому шаг — по строкам тела: строка, срезанная окном,
// встаёт целиком у противоположного края. Арифметика одна, без окна, в DIP
// подложки (note_frame.h): тело лежит на ней в поле kNotePadding. Прокручивает
// и обрезает цель до конца прокрутки всплывашка (NotePopup в Reader).

#include <span>

#include "bukvitsa/reader/note_scroll_kind.h"

// Последним: строки тела — из заголовков вёрстки, а те ведут к импорту, после
// которого стандартный заголовок MSVC уже не принимает.
#include "bukvitsa/typography/note.h"

namespace bukvitsa::reader {

/// Новый верх окна прокрутки сноски, DIP подложки.
///
/// Строка занимает на подложке свой подъём и вынос и по половине интерлиньяжа
/// над и под ними: надстрочные знаки рисуются выше подъёма, и край окна по
/// самому подъёму срезал бы их чернила.
///
/// Окно вниз — до строки, которую окно срезало снизу: она становится верхней;
/// окно вверх — до строки, срезанной сверху: она становится нижней. Строки на
/// краю нет или она выше окна — шаг на окно без строки у края, чтобы
/// прочитанное осталось на виду, но не меньше полуокна. Строка — на соседнюю
/// строку; строка, которую такой шаг срезал бы, встаёт целиком у края окна, а
/// строка выше окна идёт по полуокну: прыжок через неё пропустил бы её
/// середину. Верх первой строки — край подложки: поле над ней прокручивается
/// вместе с ней. Начало — ноль, конец — рост подложки: дальше конца прокрутки
/// окно не пойдёт, и обрезает цель само окно. Сноска, которая помещается, не
/// прокручивается: всегда ноль.
///
/// @param bodyLines    строки тела сноски сверху вниз, базовые линии — от
///                     верха тела (typography::NoteLayout::lines).
/// @param viewTop      верх окна, от которого шагать, DIP подложки.
/// @param windowHeight высота окна прокрутки, DIP.
/// @param paperHeight  рост подложки — тела с полем над ним и под ним, DIP.
double noteScrollTarget(std::span<const typography::NoteLine> bodyLines, double viewTop,
                        double windowHeight, double paperHeight, NoteScroll scroll);

}  // namespace bukvitsa::reader
