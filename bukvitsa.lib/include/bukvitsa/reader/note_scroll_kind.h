#pragma once
// Род прокрутки открытой сноски с клавиатуры — отдельно от расчёта цели
// (note_scroll.h): его знают карта команд, ведущий и холст, а строки тела,
// по которым считается цель, — только тот, кто сноску показывает.

namespace bukvitsa::reader {

/// Куда прокрутить открытую сноску.
enum class NoteScroll {
    LineDown,   ///< на строку вниз
    LineUp,     ///< на строку вверх
    PageDown,   ///< на окно вниз
    PageUp,     ///< на окно вверх
    ToStart,    ///< к началу
    ToEnd,      ///< к концу
};

}  // namespace bukvitsa::reader
