#pragma once
// PageCanvas — то, что ведущий полосы (`BookPresenter`) просит у того, кто
// рисует и анимирует: Reader отвечает композитором и Direct2D, тест —
// записью вызовов.
//
// Интерфейс — ведущего и объявлен рядом с ним: в нём ровно то, что нужно
// порядку шагов переворота, перевёрстки и прыжка, и ничего о том, как это
// выглядит. Что рисовать, холст берёт у ведущего в миг вызова — поток
// страниц, бумагу, обложку страницы, масштаб; своего мнения о книге, месте
// чтения и теме у него нет. Листы, растры, тени, снимок обложки, сноска на
// экране — холста, и ведущий о них не знает.
//
// Владение: холст — владельца полосы и живёт не дольше ведущего; ведущий
// держит его ссылкой с той минуты, как холст встал под него, и до той, когда
// умерла их связь (`BookPresenter::attachCanvas`, `CanvasAttachment`).

// Последним: поток страниц ведёт к импорту модуля книги, после которого
// стандартный заголовок MSVC уже не принимает.
#include "bukvitsa/reader/page_flow.h"

namespace bukvitsa::reader {

/// Холст полосы: две точки вокруг шага книги в перевороте, конечное состояние
/// всего, что летит, рисунок нынешнего разворота, вид страницы, сноска и вход
/// в чтение. Реализует тот, у кого есть окно; ведущий держит ссылку.
class PageCanvas {
public:
    /// Переворот начинается: книга ещё стоит на уходящем развороте, и всё,
    /// что берётся с него, берётся сейчас. Встречное листание холст здесь
    /// сперва доводит до конца — серия переворотов идёт в одну сторону.
    virtual void turnStarting(bool forward) = 0;

    /// Книга шагнула, новый разворот нарисован (`redraw`) — переворот
    /// пускается, если ему есть как выглядеть.
    virtual void turnStarted(bool forward) = 0;

    /// Всё, что летит, — в конечное состояние, синхронно: на нём следующей
    /// строкой стоят перевёрстка и прыжок — шаг книги без анимации.
    virtual void finishTurns() = 0;

    /// Рисует нынешний разворот потока страниц туда, где он сейчас живёт, и
    /// одевает в него страницы, если им положено. Меры ещё нет — ничего.
    virtual void redraw() = 0;

    /// Вид страницы сменился — тема, список обложек или предпросмотр: всё,
    /// что сделано из прежнего вида (тени переворота, карта изгиба), холст
    /// забывает. Перерисовывать — отдельно (`redraw`).
    virtual void restyle() = 0;

    /// Показывает сноску этого знака рядом с ним. Сама показанная сноска не
    /// прячется — ни по таймеру, ни по щелчку, ни при смене чего-нибудь на
    /// холсте: прячет её только `hideNote`, когда попросит ведущий. Иначе
    /// ведущий считал бы её открытой, а её бы не было, и Escape и щелчок
    /// решали бы по неправде.
    /// @return показана ли: тело, из которого нечего набрать, не показывается,
    ///         а прежняя сноска при этом уходит.
    virtual bool showNote(const PageFlow::NoteHit& noteHit) = 0;

    /// Прячет показанную сноску.
    virtual void hideNote() = 0;

    /// Полоса стала текущим экраном (`entersReading`) или перестала им быть:
    /// показ страниц, источник ожиданий чтения, задник окна. Уходя, холст
    /// сперва доводит до конца всё, что летит; входя — тоже, для покоя новой
    /// серии. Нарисовать разворот при входе — отдельно (`redraw`).
    virtual void activate(bool entersReading) = 0;

protected:
    ~PageCanvas() = default;
};

}  // namespace bukvitsa::reader
