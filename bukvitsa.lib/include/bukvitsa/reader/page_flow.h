#pragma once
// PageFlow — поток страниц открытой книги: мера полосы, число колонок, лента
// колонок через границы глав, показанный разворот и место чтения.
//
// Это то, что полоса набора показывает, без того, как она это показывает:
// здесь решается, сколько колонок и какой они ширины, с какой колонки
// начинается разворот, куда ведёт переворот и что пишет колонцифра, — а
// рисует, анимирует и принимает ввод тот, кто поток держит (полоса Reader).
// Окна поток не знает, поэтому каждое его правило проверяется обычным тестом
// на настоящей книге.
//
// Место чтения хранится в символах книги, а не в номере страницы: страница
// меняется от кегля, полей и размера окна, символ — нет. Его ставят только
// действия читателя — открытие книги, листание, прыжок; перевёрстка находит
// по нему колонку и саму букву не двигает.
//
// Владение: книгу поток держит общей (`std::shared_ptr`) — пагинатор внутри
// неё указывает в её же узлы, а разворот — в страницы её глав. Разворот живёт
// до следующей перевёрстки, перехода или смены книги.

#include <chrono>
#include <cstdint>
#include <memory>
#include <optional>
#include <span>
#include <vector>

// Последним: книга ведёт к импорту модуля книги, после которого стандартный
// заголовок MSVC уже не принимает.
#include "bukvitsa/reader/book.h"

namespace bukvitsa::reader {

class PageFlow {
public:
    /// Место в непрерывной ленте колонок книги: глава и колонка внутри неё.
    /// Разворот задаётся своей левой колонкой, а лента склеивается из колонок
    /// соседних глав, идущих подряд без пропуска на стыке.
    struct Column {
        size_t chapter = 0;
        size_t index = 0;

        friend bool operator==(const Column&, const Column&) = default;
    };

    /// Точка на полосе в DIP от её левого верхнего угла. Своя, а не оконная:
    /// поток окна не знает.
    struct Point {
        float x = 0.0f;
        float y = 0.0f;
    };

    /// Знак сноски под точкой: куда он ведёт и откуда вставать всплывашке.
    struct NoteHit {
        const fb3::Node* target = nullptr;   ///< nullptr — мимо знака
        Point anchor;                        ///< середина знака под его строкой
    };

    /// Показанный разворот: колонки слева направо, по странице на колонку.
    /// Страницы — из кэша глав книги; книга держит их главы, пока они здесь.
    struct Spread {
        /// До columns() штук; меньше — только у самого конца книги.
        std::vector<const typography::Page*> pages;
        /// Сколько первых колонок принадлежит текущей (левой) главе —
        /// остальные пришли со стыка, из следующей.
        size_t ownColumns = 0;
    };

    /// Что пишет колонцифра. Номера — по левой главе: разворот на стыке
    /// кончается колонками следующей, но «стр. X из M» называет ту главу, где
    /// стоит читатель, и в номера соседней не залезает.
    struct Status {
        size_t chapter = 0;            ///< глава, с нуля
        size_t first = 0;              ///< левая колонка разворота в главе, с нуля
        size_t own = 1;                ///< сколько колонок разворота её — не меньше одной
        /// Страниц в главе (не меньше одной). Пусто, пока хвост главы не
        /// досчитан: число, которое сейчас сменится другим, хуже честного
        /// молчания.
        std::optional<size_t> total;
        float progress = 0.0f;         ///< 0..1 по символам всей книги
    };

    PageFlow() = default;
    PageFlow(const PageFlow&) = delete;
    PageFlow& operator=(const PageFlow&) = delete;

    /* ---------------- книга ---------------- */

    /// Открывает книгу на этом символе. Вёрстки ещё нет — её делает
    /// relayout(), когда известны мера и стиль.
    void open(std::shared_ptr<Book> book, uint32_t charOffset);

    /// Отпускает книгу: разворот пуст, место чтения — ноль.
    void close();

    /// Открыта ли книга. Без книги поток честно отвечает «символ нулевой», и
    /// записать этот ноль значило бы стереть место, где читатель остановился.
    bool isOpen() const { return static_cast<bool>(book_); }

    Book* book() const { return book_.get(); }

    /// Книга в блоках — то, на чём стоят оглавление и поиск. Пусто без книги.
    std::span<const typography::Block> blocks() const;

    /* ---------------- мера и стиль ---------------- */

    /// Размер полосы в DIP — всё окно. Масштаб экрана сюда не входит: в
    /// пиксели DIP переводит тот, кто рисует. Перевёрстка — отдельно,
    /// relayout().
    void resize(float width, float height);
    float width() const { return width_; }
    float height() const { return height_; }

    /// Вид набора: кегль в DIP, интерлиньяж множителем кегля и боковое поле
    /// долей ширины полосы. Приводится к пределам настроек. Перевёрстка —
    /// отдельно, relayout().
    /// @return изменилось ли что-нибудь.
    bool setStyle(float fontSize, float lineHeightMultiplier, float marginFraction);
    float fontSize() const { return fontSize_; }
    float lineHeight() const { return lineHeight_; }
    float marginFraction() const { return marginFraction_; }

    /// Перевёрстка под нынешние меру и стиль: решает число колонок, верстает
    /// текущую главу начисто до места чтения и видимого разворота, встаёт на
    /// колонку с буквой места чтения и собирает разворот. Саму букву не
    /// двигает. Одна глава стоит единицы миллисекунд — зовётся прямо в
    /// обработчике события; остаток главы — порциями, advanceTail().
    ///
    /// @param windowResize перевёрстка от размера окна, а не от кегля или
    ///        полей: только ей полагается гистерезис числа колонок.
    /// @return свёрстано ли: без книги или при пустой мере вёрстки нет, и
    ///         разворот пуст.
    bool relayout(bool windowResize = false);

    /// Сколько колонок сейчас. Решается длиной строки в знаках при каждой
    /// перевёрстке.
    int columns() const { return columns_; }

    /// Сколько знаков вышло бы в строке, раздели мы место между полями на
    /// столько колонок, — то, чем решается их число.
    float lineChars(int columnCount) const;

    /* ---------------- разворот и место чтения ---------------- */

    const Spread& spread() const { return spread_; }

    /// Левая колонка показанного разворота.
    Column anchor() const;

    /// Номер левой колонки разворота внутри текущей главы.
    size_t page() const { return page_; }

    /// Буква, до которой дошёл читатель: начало колонки, на которую он
    /// перелистнул или прыгнул, либо место, с которого открыли книгу. В файл
    /// состояния книги уходит она.
    uint32_t position() const { return position_; }

    /// Сколько страниц текущей главы уже набрано; настоящим число становится,
    /// когда isComplete().
    size_t pageCount() const;

    /// Досчитана ли текущая глава — известно ли «из M».
    bool isComplete() const;

    /// 0..1 по символам книги.
    float progress() const;

    /// Числа колонцифры для показанного разворота.
    Status status() const;

    /* ---------------- переходы ---------------- */

    /// Куда ведёт переворот на разворот вперёд или назад по ленте, — без
    /// самого переворота: книга остаётся на месте, пока не позовут show().
    /// Через границу главы лента идёт непрерывно, это обычный шаг. Назад у
    /// начала книги прижимает к самому первому развороту.
    /// @return пусто у края книги: листать некуда.
    std::optional<Column> turnTarget(bool forward);

    /// Колонка, в которой лежит символ: наводит текущую главу на место и
    /// верстает её до него. Ею идут закладка, оглавление, находка поиска и
    /// края книги. Сменив главу, сбрасывает разворот — он указывал в прежнюю
    /// раскладку; книгу на колонку ставит show().
    Column columnOf(uint32_t charOffset);

    /// Ставит книгу на эту колонку ленты: наводит главу (соседняя, уже
    /// разложенная лентой, остаётся со своей вёрсткой), ставит место чтения на
    /// начало колонки и собирает разворот. Им кончаются и прыжок, и
    /// переворот: анимировать переход — забота рисующего.
    void show(const Column& target);

    /* ---------------- хвост главы ---------------- */

    /// Не досчитана ли текущая глава: её «из M» ещё неизвестно.
    bool needsTail() const;

    /// Порция досчёта текущей главы — не дольше срока плюс один блок. Звать в
    /// простое потока: когда он свободен, знает только тот, у кого есть окно.
    /// Показанного не меняет — растёт лишь число страниц главы.
    /// @return true, пока есть что досчитывать.
    bool advanceTail(std::chrono::steady_clock::duration slice);

    /* ---------------- геометрия полосы ---------------- */

    /// Боковое поле в DIP.
    float margin() const;

    /// Отступ набора сверху и полоса колонцифры снизу, в DIP.
    float verticalMargin() const;

    /// Левый край колонки с этим номером внутри разворота.
    float columnLeft(size_t index) const;

    /// Корешок — середина средника между колонками разворота: то место, до
    /// которого доходит кромка в книжном листании.
    float spine() const;

    /// Знак сноски под точкой разворота — или пусто (target == nullptr).
    NoteHit noteAt(Point point) const;

private:
    /// Есть ли что верстать: книга открыта и в ней хоть одна глава.
    bool readable() const;

    /// Средняя ширина знака нынешним шрифтом и кеглем — мерой движка книги.
    float characterWidth() const;

    /// Сколько колонок показывать. Решает длина строки в знаках; ширину
    /// колонок это не трогает — её задают поля.
    /// @param sticky держаться за нынешнее число в пределах гистерезиса.
    int chooseColumns(bool sticky) const;

    /// Глава по индексу, разложенная под нынешнюю полосу и досчитанная хотя бы
    /// до `pages` колонок. Ею лента достаёт колонки соседних глав: соседняя,
    /// оставшаяся в кэше от прежней полосы, при этом перекладывается заново.
    typography::Chapter& chapterLaidTo(size_t index, size_t pages);

    /// Двигает позицию на одну колонку ленты вперёд или назад, перешагивая
    /// границы глав (и пустые главы). false — уже у самого края книги.
    bool ribbonStep(Column& pos, bool forward);

    /// Двигает позицию на целый разворот — столько колонок, сколько на экране.
    /// Вперёд у конца книги — false и позиция на месте; назад у начала —
    /// прижимает к самому первому развороту.
    bool ribbonSpread(Column& pos, bool forward);

    /// Собирает показанный разворот — до columns_ колонок ленты от левой
    /// (anchor), при нужде из следующих глав. Заодно чистит кэш глав.
    void buildSpread();

    std::shared_ptr<Book> book_;

    /// Левая колонка показанного разворота — её номер внутри текущей главы.
    /// Разворот тянется отсюда вправо по ленте и, если глава кончилась, дальше
    /// идут колонки следующей. К числу колонок номер не привязан: разворот
    /// начинается ровно с той колонки, где стоит читатель, чтобы на стыке
    /// глав не пропадала колонка.
    size_t page_ = 0;

    /// Буква места чтения — см. position().
    uint32_t position_ = 0;

    /// Показанный разворот, собранный лентой (buildSpread).
    Spread spread_;

    /// Сколько колонок сейчас. Поле нужно ради гистерезиса: чтобы решить,
    /// куда идти с границы, надо знать, где стоишь.
    int columns_ = 1;

    /// Полоса, по которой считается книга. Держится потому, что соседние главы
    /// ленты и досчёт хвоста обязаны считать по той же полосе, по которой
    /// начата вёрстка.
    typography::PageStyle pageStyle_;

    float fontSize_ = 20.0f;
    float lineHeight_ = 1.45f;

    /// Боковое поле долей горизонтального размера полосы (по 7,5 % с каждой
    /// стороны по умолчанию). Долей ширины, а не кегля: поле не должно расти
    /// вместе со шрифтом — книге положено держать поля страницы, каким бы
    /// крупным ни был набор.
    float marginFraction_ = 0.075f;

    /// Размер полосы в DIP.
    float width_ = 0.0f;
    float height_ = 0.0f;
};

}  // namespace bukvitsa::reader
