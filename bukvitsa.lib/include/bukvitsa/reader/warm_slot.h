#pragma once
// Слот прогретой книги — той, которую читатель скорее всего откроет
// следующей: прочитанной с диска и уже разобранной, пока он смотрит на
// заставку. Нажатие «Продолжить чтение» после этого не ждёт ни диска, ни
// разбора — самой долгой части открытия.
//
// Держится ровно одна: греть больше нечего (продолжают одну книгу), а
// разобранная книга — это десятки мегабайт.
//
// Протокол — заказ и сверка пути. Заказ (`expect`) записывает, чью книгу
// ждём, прежде чем чтение уйдёт к диску; прогрев, вернувшись, кладёт
// разобранное (`fill`), только если ждём всё ещё её. Открытие книги заказ
// снимает (`cancel`) — и прогрев, шедший для неё же, выбросит своё, вместо
// того чтобы оставить в памяти вторую копию уже открытой книги. Отдаётся
// книга только своему пути (`take`), и один раз.
//
// Слот не читает и не ждёт: чтение — у рабочего места (`Workspace::readBook`),
// ожидание — у сценария, который его зовёт. Здесь только то, чья книга и
// можно ли её отдать, — то, на чём гонка «открыли, пока грелось» и решается.

#include <cstdint>
#include <filesystem>
#include <memory>
#include <optional>

// Последним: рабочее место (`Warmed`) несёт импорт.
#include "workspace.h"

namespace bukvitsa::reader {

/// Одна прогретая книга и путь, под которым её ждут. Владеет книгой, пока её
/// не взяли.
class WarmSlot {
public:
    /// Заказ: ждём книгу по этому пути. Прогретая прежде выбрасывается — слот
    /// держит одну.
    void expect(std::filesystem::path path);

    /// Прогрев вернулся: кладёт книгу, только если ждём всё ещё её. Заказ снят
    /// или сменился — книга выбрасывается здесь же.
    void fill(const std::filesystem::path& path, std::shared_ptr<Book> book, uint64_t fileSize);

    /// Лежит ли прогретая книга этого пути — без того, чтобы её брать.
    bool holds(const std::filesystem::path& path) const;

    /// Отдаёт прогретую книгу этого пути и опустошает слот; другой путь или
    /// прогрев не кончился — пусто, и слот остаётся как был.
    std::optional<Warmed> take(const std::filesystem::path& path);

    /// Снимает заказ и выбрасывает прогретое: книга открывается своей дорогой.
    void cancel();

private:
    std::filesystem::path wanted_;   ///< чью книгу греем или уже прогрели; пусто — никого
    Warmed warmed_;                  ///< она же разобранная; пусто, пока прогрев идёт
};

}  // namespace bukvitsa::reader
