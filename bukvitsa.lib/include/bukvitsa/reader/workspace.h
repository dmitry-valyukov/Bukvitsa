/// Чем кончился запуск: настройки, обложки и реестр уже в полях рабочего
/// места, а здесь — что при этом пошло не так, и книга, которую можно
/// продолжить читать (пусто — нечего).
struct Started {
    std::vector<Notice> notices;
    std::filesystem::path lastBook;
};

/// Что отдаёт чтение книги: открытая книга, то, что от документа нужно
/// регистрации, и размер файла. Самого документа здесь нет: книга забрала у
/// него своё, описание и обложку чтение сняло раньше неё, а остальное умерло
/// с ним. Пустой не бывает: книга не прочиталась — значения нет вовсе, а
/// есть исключение чтения.
struct LoadedBook {
    not_null<intrusive_ptr<Book>> book;
    fb3::Description description;     ///< описание книги — для реестра
    std::optional<BookCover> cover;   ///< обложка — для кэша; пусто, если её у книги нет
    uint64_t fileSize = 0;            ///< размер файла: его записывает реестр
};

/// Что вернула регистрация книги: запись реестра, была ли книга новой и не
/// вернулась ли она из «не найдена».
struct Registered {
    BookEntry entry;
    bool isNew = false;       ///< в реестре её не было — полке есть что добавить
    bool isChanged = false;   ///< запись новая или другая — реестр переменился
    bool restored = false;    ///< была помечена «не найдена»: файл прочитан, пометка снята
};

/// Событие рабочего места о регистрациях книг. На него смотрят, как
/// на поле: `on_change` и `remove_change` — подписка и снятие, а держатель
/// подписки у владельца — `change_watch`. Зовёт его только рабочее место.
template <class Argument>
class WorkspaceEvent {
public:
    using changed_event = event<void(Argument) noexcept>;

    template <class F>
    event_token on_change(F&& callback) {
        return event_.add(std::forward<F>(callback));
    }

    bool remove_change(event_token& token) { return event_.remove(token); }

    // Снятие держателя, встроенного в подписчика, — по его узлу: так снимает себя change_watch.
    bool remove_change(typename changed_event::func_t& node) { return event_.remove(node); }

private:
    friend class Workspace;

    changed_event event_;
};

/// Открытая книга со стороны модели: запись реестра и состояние — место
/// чтения и закладки (чистый лист, если книгу ещё не открывали).
struct Opened {
    BookEntry entry;
    BookState state;
};

/// Чем кончился обход каталога — при добавлении и при перепроверке; у
/// перепроверки всех каталогов — сумма по ним: что он нашёл, что пометил и
/// что отдал регистрации. Что из отданного встало, а что нет, — не здесь:
/// обход шагов не ждёт, об этом говорят события рабочего места
/// (`bookRegistered`, `registrationRefused`). По нему видно и то, что
/// неизменное не читалось: такой файл есть в `listed`, а в `queued` его нет.
struct ScanReport {
    uint32_t listed = 0;     ///< книг (`*.fb3`) в листинге каталога
    uint32_t queued = 0;     ///< прочитано, разобрано и отдано регистрации: новые и изменённые
    uint32_t marked = 0;     ///< записей каталога, чьего файла нет: помечены «не найдена»
    uint32_t restored = 0;   ///< записей, чей файл вернулся: пометка снята
    /// Что не прочиталось — путь и причина: файл, который не прочитался, книга
    /// FB3, которая не разобралась или чья обложка не прочиталась из пакета
    /// (такая книга регистрации не отдаётся), каталог перепроверки, который не
    /// перечислился. Не-книга (`*.fb3`, чьи байты не zip или чей пакет прочитан
    /// чисто, а связи Book в нём нет, — `fb3::NotFb3Book`) сюда не попадает: её
    /// пропускают молча.
    std::vector<std::wstring> unread;

    /// Пометки переменили реестр в памяти — его пора записать. Перемены от
    /// регистраций отданных книг приходят событием `bookRegistered`.
    bool changed() const noexcept { return marked + restored != 0; }
};

/// Каталог данных по умолчанию: `%LOCALAPPDATA%\Bukvitsa\Reader`. Корень общий
/// для семейства — рядом однажды встанет Writer; не Roaming: в реестре лежат
/// локальные пути и кэш обложек, и роуминг перенёс бы на другую машину битые
/// ссылки и лишние мегабайты. Переменная окружения `BUKVITSA_DATA` подменяет
/// каталог целиком: прогон драйвером (`tools\drive.ps1 -DataDir`) идёт на
/// подопытных данных, не трогая настоящих.
std::filesystem::path standardDataDirectory();

class Workspace {
public:
    /// Рабочее место в этом каталоге — пустое: его наполнит запуск (`start`).
    /// @param appStop токен общего источника приложения: под ним
    ///        регистрации книг обхода каталога ждут замка. Источник самого
    ///        обхода живёт в его сценарии и уходит вместе с ним, а отданные
    ///        обходом книги ещё должны встать; эти ожидания кончает только
    ///        выход приложения.
    Workspace(std::filesystem::path directory, wxl::async::cancellation_token appStop);

    /// Регистрация ещё идёт (`registering`) — её кадр держит это рабочее
    /// место, и уйти раньше неё — остановка.
    ~Workspace();

    Workspace(const Workspace&) = delete;
    Workspace& operator=(const Workspace&) = delete;

    // ---- где что лежит ----

    const std::filesystem::path& directory() const noexcept { return directory_; }
    std::filesystem::path settingsPath() const;    ///< settings.xml
    std::filesystem::path libraryPath() const;     ///< library.xml
    std::filesystem::path skinsPath() const;       ///< skins.xml
    std::filesystem::path skinDirectory() const;   ///< skins\ — снимки обложек читателя
    std::filesystem::path coverDirectory() const;  ///< cache\ — обложки книг из реестра
    /// books\{guid}.xml. Имя файла — guid и ничего больше: он наш, выдан
    /// `CoCreateGuid`, и в нём не может оказаться ни разделителя пути, ни
    /// двоеточия. Названия книги здесь нет намеренно — оно чужое.
    std::filesystem::path statePath(u16_view guid) const;
    /// Снимок обложки: встроенная — из Assets рядом с исполняемым, читателя —
    /// из skins\.
    std::filesystem::path skinImagePath(const Skin& skin) const;

    // ---- модели ----

    Settings settings;   ///< настройки вида и запуска: наблюдаемые поля, к ним привязаны контролы
    Library library;     ///< реестр книг
    Skins skins;         ///< обложки читателя

    // ---- запуск ----

    /// Читает настройки, обложки и реестр. Нет файла — первый запуск, молча;
    /// файл не читается или не разбирается — слово читателю в `notices`;
    /// испорченный остаётся рядом копией `.bad`, а первая же запись заменит
    /// его. Обложки, чьи кромки в skins.xml неверны, реестр показывает
    /// исправленными (`Skins::loadFrom`), а запуск кладёт рядом копию файла —
    /// так же, `.bad`, — и называет их одним сообщением в `notices`: строкой
    /// на обложку с тем, что исправлено, путями файла и копии и тем, что
    /// первое сохранение или удаление обложки перепишет файл исправленным.
    /// Сам файл запуск не переписывает. Заодно ищет книгу, которую можно
    /// продолжить (`lastBookPath`).
    ///
    /// Токен слушает только этот поиск. Три файла читаются без него: из
    /// моделей, которые они наполняют, потом пишется всё — настройки и при
    /// закрытии окна, — и недочитанная модель легла бы на диск умолчаниями
    /// поверх файлов читателя.
    wxl::async::task<Started> start(wxl::async::cancellation_token token);

    // ---- книги ----

    /// Читает и разбирает книгу: байты — операцией, разбор — здесь. Файл не
    /// прочитался — `last_error`; не разобрался — исключение разбора;
    /// попросили остановиться до разбора — отмена, и книга не разбирается.
    /// Документ разбора живёт только здесь: описание и копию обложки чтение
    /// снимает с него для регистрации, остальное нужное забирает книга.
    wxl::async::task<LoadedBook> readBook(std::filesystem::path path, wxl::async::cancellation_token token);

    /// Регистрирует книгу — шагом под замком регистраций рабочего места. Замок
    /// один на рабочее место и отдаётся по порядку прихода: регистрация,
    /// пришедшая, пока идёт шаг другой, ждёт его конца. Две регистрации одной
    /// книги разом (перепроверка каталога и «Продолжить чтение») потому не
    /// пишут одну обложку через один временный файл и не заводят книге двух
    /// guid: вторая, дождавшись замка, регистрирует свои входы, а реестр
    /// узнаёт ту же книгу (`Library::findSame`) и решает её запись по себе,
    /// каким его оставил шаг впереди, — побеждает последняя регистрация. У
    /// того же файла реестр держит своё правило: каталог — всегда, время
    /// правки — при том же размере, так что регистрация без них (открытие
    /// файлом после обхода) их не теряет.
    ///
    /// Шаг: запись, какой её сделает реестр (`Library::entryFor`), затем
    /// обложка в кэше под её guid — только для новой или изменённой записи и
    /// раньше, чем карточка встанет в реестр: полка берёт картинку из файла в
    /// тот же миг, — затем запись в реестре (`Library::add`). Между ними —
    /// ожидание записи обложки, и ни один другой шаг на нём не идёт: реестр
    /// отдаёт ту же запись, что задумана, а иное — нарушенный инвариант,
    /// остановка. Файл реестра шаг не пишет — его пишет вызывающий
    /// (`saveLibrary`); переменился реестр — событие `bookRegistered`, раньше,
    /// чем регистрация вернётся.
    ///
    /// Токен кончает ожидание замка: под отменённым регистрация не
    /// начинается, отменённая на ожидании кончается
    /// `operation_canceled_exception`, и реестр книги не узнаёт. Шаг, взявший
    /// замок, — задача самого рабочего места, а вызывающий лишь ждёт её
    /// конца: токена шаг больше не слушает, и вызывающий, ушедший раньше
    /// (его задачу сбросили), шага не обрывает — он доходит до реестра и
    /// только тогда отдаёт замок (`registering`). Запись обложки токена не
    /// берёт — оборванная запись есть файл, которому не верят, — а обложка,
    /// записанная без своей записи в реестре, осталась бы в `cache\` сиротой;
    /// замок, отданный посреди записи, пустил бы следующий шаг писать тот же
    /// файл.
    ///
    /// Сбой записи обложки — `last_error` у ждущего: реестр книги не узнаёт,
    /// замок переходит к следующему. О каждом таком сбое — ждёт его кто-то
    /// или уже нет — рабочее место говорит само, один раз, событием
    /// `registrationRefused`, и ждущему повторять его незачем. Иного шаг не
    /// обещает.
    /// @param characterCount полный размер книги в символах — знаменатель
    ///        прогресса на полке.
    /// @param file путь и размер; время правки и каталог — у обхода каталога.
    wxl::async::task<Registered> registerBook(fb3::Description description, uint32_t characterCount,
                                              std::optional<BookCover> cover, BookFile file,
                                              wxl::async::cancellation_token token);

    /// Шаг регистрации поставил книгу в реестр или переменил её запись
    /// (новая, другая, вернувшаяся из «не найдена»): реестр в памяти
    /// переменился — его пора записать. Зовётся раньше, чем регистрация
    /// вернётся.
    WorkspaceEvent<const Registered&>& bookRegistered() noexcept { return bookRegistered_; }

    /// Шаг регистрации не удался — обложка не записалась. Говорит о каждом
    /// таком шаге одно рабочее место, один раз: и о книге обхода, которого
    /// никто не ждёт, и о прямой регистрации (`registerBook`), чей ждущий
    /// получает ещё и `last_error` или уже ушёл. Строка — путь и причина, как
    /// у `ScanReport::unread`.
    WorkspaceEvent<const std::wstring&>& registrationRefused() noexcept { return registrationRefused_; }

    /// Идёт ли регистрация, которую держит рабочее место: шаг под замком —
    /// любой, и тот, чей ждущий ушёл, — или регистрация книги обхода, ждущая
    /// замка.
    bool registering() const noexcept;

    /// Открывает со стороны модели книгу, уже вставшую в реестр (запись — та,
    /// что отдал шаг её регистрации): состояние, затем последняя книга в
    /// настройках — в памяти. Файл настроек не пишет: его пишет цикл
    /// приложения (`saveSettings`), и будит его вызывающий. Настройки
    /// указывают на новую книгу раньше, чем она встанет на полосу, — место
    /// чтения пишется не по ним, а под guid мест книги на полосе
    /// (`BookPlaces::guid`).
    ///
    /// Под отменённым токеном открытие не начинается. Отмена, пришедшая на
    /// чтении состояния, кончает его отменой, что бы чтение ни ответило, — и
    /// тогда, когда ответ успел раньше отмены: тот, кто отменил, открытия
    /// больше не ждёт, и книга на полосу не встаёт. Настройки ставятся после
    /// последнего ожидания, так что открытие, отменённое или брошенное на
    /// ожидании, их не трогает, а у вызывающего от них до смены книги ожиданий
    /// нет.
    ///
    /// Запись — ссылкой: её держит кадр ждущего, а тот стоит на `co_await`
    /// этой корутины до её конца.
    wxl::async::task<Opened> openBook(const BookEntry& entry, wxl::async::cancellation_token token);

    /// Перепроверяет наблюдаемый каталог (из `library.folders()`); подкаталоги
    /// не обходятся. Листинг `*.fb3` с размером и временем правки сводится с
    /// записями этого каталога (`BookEntry::folder`): записи, чьего файла в
    /// листинге нет, помечаются «не найдена», а чей есть — с пометки
    /// снимаются, одним ходом, до первого чтения. Файл с записью этого
    /// каталога, тем же размером и тем же известным временем — тот же: его не
    /// читают, не разбирают и обложку его не пишут. Остальные — новые и
    /// изменённые — читаются, разбираются и отдаются регистрации по одному;
    /// новая книга встаёт карточкой в конец `library.cards()` своим шагом —
    /// полка, привязанная к ним, растёт по ходу. Файл реестра не
    /// пишет: его пишет цикл приложения (`saveLibrary`), и будит его
    /// вызывающий — по отчёту (пометки) и по событию `bookRegistered`.
    ///
    /// Каталога нет вовсе — нет и его книг: все его записи помечаются, и
    /// вернётся каталог — снимет пометки следующая перепроверка. Иначе не
    /// перечислился — `last_error`, и записи не тронуты. Нечитаемый файл,
    /// книга FB3, которая не разобралась, и книга, обложка которой не
    /// прочиталась из пакета, попадают в `unread`, не-книга молча
    /// пропускается: обход идёт дальше; книга, чья обложка не записалась, —
    /// событием `registrationRefused`.
    ///
    /// Каждая прочитанная книга отдаётся регистрации (`registerBook`), и
    /// обход её шага не ждёт: он читает следующую, пока пишется обложка
    /// прежней. Регистрации держит рабочее место (`registering`) и ведёт их
    /// под общим токеном приложения, а не под токеном обхода: источник обхода
    /// живёт в сценарии, который его начал, и уходит вместе с ним — раньше,
    /// чем встанут отданные книги. Что встало и что не встало, обход не
    /// знает — это говорят события рабочего места (`bookRegistered`,
    /// `registrationRefused`).
    ///
    /// Отмена кончает обход на ближайшем чтении: под отменённым токеном он не
    /// начинается, листинг, взятый после неё, с записями не сводится — и тот,
    /// чей ответ успел раньше отмены, — а прочитанное после неё не разбирается
    /// и регистрации не отдаётся. Отданные до неё книги регистрируются — их
    /// регистрации отмена обхода не трогает; ожидание замка у них кончает
    /// только выход приложения, а шаг, взявший замок, доходит до реестра и
    /// тогда. Обложка в кэше — восстановимое и ни к чему не обязывает;
    /// обязывает реестр в памяти, который полка уже показала: его книги,
    /// зарегистрированные до отмены, вызывающий пишет и после неё.
    wxl::async::task<ScanReport> scanFolder(std::filesystem::path folder, wxl::async::cancellation_token token);

    /// «Добавить каталог»: каталог становится наблюдаемым
    /// (`library.addFolder`), и его книги обходятся, как перепроверкой
    /// (`scanFolder`). Наблюдаемым он становится, лишь когда перечислился:
    /// каталог, которого не прочесть, — `last_error`, и реестр его не
    /// запоминает; отмена — так же, как у перепроверки: отменённого на
    /// листинге каталога реестр тоже не запоминает.
    wxl::async::task<ScanReport> addFolder(std::filesystem::path folder, wxl::async::cancellation_token token);

    /// Перепроверяет наблюдаемые каталоги — все, что были в
    /// `library.folders()` к началу, один за другим (`scanFolder`); отчёт —
    /// сумма. Каталог, который не перечислился, — строкой в `unread`, и
    /// перепроверка идёт к следующему. Под отменённым токеном не начинается,
    /// отменённая кончается на ближайшем чтении, как обход одного каталога.
    wxl::async::task<ScanReport> rescanFolders(wxl::async::cancellation_token token);

    /// Книга, которую можно продолжить читать: путь из настроек, если файл на
    /// месте, иначе по guid из реестра. Пусто — нечего.
    wxl::async::task<std::filesystem::path> lastBookPath(wxl::async::cancellation_token token);

    /// Состояние книги; нет файла — чистый лист, это не ошибка.
    wxl::async::task<BookState> readState(u16_view guid, wxl::async::cancellation_token token);
    wxl::async::task<> saveState(u16_text guid, BookState state);

    /// Текст настроек и реестра собирается в момент вызова, до ожидания: на
    /// диск уходит решённое, а не то, что читатель поменяет за время записи.
    /// Зовёт их — и `saveState` — один писатель на файл: у читалки её цикл
    /// записи.
    wxl::async::task<> saveSettings();
    wxl::async::task<> saveLibrary();

    // ---- обложки читателя ----

    /// Сохраняет обложку: у новой — копия снимка в `skins\` под новым guid с
    /// родным расширением (имена обложек выбирает читатель, они повторяются;
    /// guid — нет), у правки копия уже лежит; затем запись реестра.
    ///
    /// Чтение снимка — до записей: под отменённым токеном сохранение не
    /// начинается, отмена на чтении ничего не пишет, а с первой записи —
    /// копии снимка — оно доходит до строки реестра, которая на копию
    /// ссылается. Реестр не записался — сбой (`last_error`), и реестр в
    /// памяти тот же, что до вызова, если под этим именем за время записи
    /// ничего нового не легло; копия снимка остаётся лежать.
    wxl::async::task<> saveSkin(Skin skin, std::filesystem::path photo, wxl::async::cancellation_token token);

    /// Убирает обложку из реестра и пишет его; не было — ничего. Снимок
    /// остаётся в `skins\`: копия не принадлежит одной обложке — мастер, открыв
    /// обложку и сохранив её под другим именем, заводит вторую с тем же файлом,
    /// а лишний файл на диске дешевле сломанной обложки.
    ///
    /// Чтений нет: под отменённым токеном удаление не начинается — реестр не
    /// тронут, — а начатое доходит до записи реестра. Не записался — сбой
    /// (`last_error`), и обложка снова в реестре в памяти, на прежнем месте.
    wxl::async::task<> deleteSkin(u16_view name, wxl::async::cancellation_token token);

    /// Снимок из файла — или почему его нет: байты операцией, раскодирование
    /// целиком в системном пуле (`decodeImageAsync`), так что снимок, битый в
    /// данных, а не в заголовке, — тоже не картинка; больше бюджета памяти —
    /// свой отказ, с размером из заголовка. Вердикт и снимок приходят вместе:
    /// проба мастера и подложка — одно чтение и одно раскодирование, а не
    /// проба, а за ней показ, который читает и раскодирует файл заново.
    ///
    /// Под отменённым токеном не начинается; отмена на чтении кончает его
    /// отменой, на раскодировании — тоже сразу, а тело раскодирования
    /// сиротеет и доживает в пуле до ближайшей полосы.
    wxl::async::task<DecodedPicture> probeImageAsync(std::filesystem::path image,
                                                     wxl::async::cancellation_token token);

    // ---- общее ----

    /// Испорченный файл — копией рядом, под тем же именем с «.bad»: байты те,
    /// что прочли и не разобрали (или разобрали, но исправили, — у реестра
    /// обложек); копия одна, прежняя перезаписывается — истории порч хранить
    /// незачем.
    wxl::async::task<> keepBrokenCopy(std::filesystem::path file, std::string bytes);

private:
    /// Сверка листинга каталога с реестром и чтение нового и изменённого —
    /// общая часть перепроверки и добавления каталога.
    wxl::async::task<ScanReport> scanListing(std::filesystem::path folder,
                                             std::vector<wxl::async::async_directory::listed_entry> listing,
                                             wxl::async::cancellation_token token);

    /// Регистрация книги, найденной обходом, — для обхода, который её не
    /// ждёт: исходы, которых никто не ждёт, становятся событиями рабочего
    /// места. Сбой записи обложки — ничего больше: о нём уже сказал шаг
    /// (`registrationRefused`); отмена — ничего: её приносит выход
    /// приложения; иное — нарушенное обещание шага, остановка.
    wxl::async::task<> registerScanned(fb3::Description description, uint32_t characterCount,
                                       std::optional<BookCover> cover, BookFile file,
                                       wxl::async::cancellation_token token);

    /// Шаг регистрации под взятым замком: запись, обложка, реестр. Замок
    /// отдаёт уход `held` — с кадром шага, в конце. Сбой записи обложки шаг
    /// называет событием `registrationRefused` и отдаёт ждущему дальше.
    wxl::async::task<Registered> registerHeld(wxl::async::async_mutex::guard held, fb3::Description description,
                                              uint32_t characterCount, std::optional<BookCover> cover,
                                              BookFile file);

    /// Начинает шаг под взятым замком задачей рабочего места (`registrations_`)
    /// и отдаёт ссылку на неё — ждущему, чтобы присоединиться.
    wxl::async::task<Registered>& startHeldStep(wxl::async::async_mutex::guard held, fb3::Description description,
                                                uint32_t characterCount, std::optional<BookCover> cover,
                                                BookFile file);

    std::filesystem::path directory_;

    /// Общий токен приложения: под ним регистрации обходов ждут замка.
    wxl::async::cancellation_token appStop_;

    WorkspaceEvent<const Registered&> bookRegistered_;
    WorkspaceEvent<const std::wstring&> registrationRefused_;

    /// Замок шага регистрации — один на рабочее место (`registerBook`). Выше
    /// задач, которые его берут, и потому переживает их: замок, ушедший
    /// запертым или с ждущим, — остановка.
    wxl::async::async_mutex registrationLock_;

    /// Шаги под замком — задачами рабочего места, а не ждущих: ждущий может
    /// уйти, а шаг должен дойти до реестра. Ниже замка: шаг держит его до
    /// конца своего кадра. Кончившиеся выметаются перед каждым новым, так что
    /// список не длиннее шагов, которые идут, — шаг под замком один, и
    /// кончившиеся держат лишь свои итоги.
    std::vector<wxl::async::task<Registered>> registrations_;

    /// Регистрации книг, найденных обходами, — последними: они трогают
    /// реестр, события и замок выше, присоединяются к шагам выше и уходят
    /// раньше всех них. Кончившиеся выметаются перед каждой новой, так что
    /// список не длиннее регистраций, которые идут.
    std::vector<wxl::async::task<>> scanRegistrations_;
};

