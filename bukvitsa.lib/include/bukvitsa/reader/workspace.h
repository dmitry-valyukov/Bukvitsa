#pragma once

// Рабочее место читалки — каталог данных и всё, что в нём живёт: настройки,
// реестр книг, обложки читателя, состояния книг, кэш картинок.
//
// Одно рабочее место — один каталог. Reader даёт ему настоящий
// (`standardDataDirectory`), тест — временный; где лежат файлы, не знает
// больше никто: пути считаются здесь и только здесь.
//
// Диск трогают только операции wxl (`read_all`, `write_all`, `exists`,
// `list`) и только из корутин этого класса; разбор идёт на потоке вызова, в
// STA-пуле, — кроме раскодирования снимков: большой снимок раскодируется
// секунды, и поток окна всё это время не брал бы ввода, так что оно идёт в
// системном пуле (`probeImageAsync`). Корутины — `task<T>`: вызывающий ждёт
// их `co_await` и получает значение, а сбой операции — исключением
// `last_error`. Окон модель не
// знает: что сказать читателю, она отдаёт словами (`Notice`), показывает их
// Reader.
//
// Кто пишет какой файл. Состояние книги, настройки и реестр книг на диск
// пишет только вызывающий — `saveState`, `saveSettings`, `saveLibrary`; задачи
// рабочего места реестр и настройки лишь меняют в памяти. У читалки писатель
// — её циклы записи, по одному на файл: сценарии, которые меняют реестр и
// настройки, идут одновременно, а две записи одного файла разом идти не
// должны — `write_all` пишет через один временный файл. Реестр обложек со
// снимками пишут сами задачи обложек (`saveSkin`, `deleteSkin`), обложки книг
// в кэше — шаг регистрации (`registerBook`), и только для новой или изменённой
// записи.
//
// Отмена — токеном вызывающего, последним параметром (`token`): его берут
// чтения, задачи, в которых есть чтение, и удаление обложки — перемена реестра
// в памяти перед его записью. Чтение под отменённым токеном не начинается,
// начатое кончается `operation_canceled_exception`. Записи токена не берут:
// оборванная запись — файл, которому не верят. Задача с токеном под
// отменённым не начинается вовсе, а её чтения стоят до первой записи или после
// последней, но не между ними: записи, которые задача начала, отмена не
// разделяет — на диск уходят все (обход каталога устроен иначе, у него
// сказано как).
//
// Наблюдаемые каталоги — у реестра (`Library::folders`), обход и перепроверка
// — один механизм (`scanFolder`): листинг с размером и временем правки,
// сверка с записями каталога и чтение только нового и изменённого.
//
// Регистрация книги (`registerBook`) — шаг под замком регистраций, одним на
// рабочее место: запись, какой её сделает реестр, обложка под её guid, затем
// запись в реестре. Пока шаг идёт, другой не начинается — регистрация,
// пришедшая в это время, ждёт замка, и замок отдаётся по порядку прихода. Так
// две регистрации одной книги разом (перепроверка каталога и открытие) не
// пишут одну обложку через один временный файл и не заводят книге два guid:
// вторая решает свою запись по реестру, каким его оставила первая. Чем
// кончился шаг, знает тот, кто его ждёт; рабочее место говорит событиями, что
// реестр переменился (`bookRegistered`) и что шаг не удался
// (`registrationRefused`). Шаг, взявший замок, — задача рабочего места, а не
// ждущего: ждущий, ушедший раньше, его не обрывает, и замок не отдаётся
// посреди записи обложки.

